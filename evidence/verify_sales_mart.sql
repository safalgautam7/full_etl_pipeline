SELECT COUNT(*) AS REGISTERED_FILES FROM RETAIL_DWH.CONTROL.FILE_MANIFEST;

SELECT COUNT(*) AS SALES_LINES, MIN(TRANSACTION_DATE) AS FIRST_TRADING_DATE,
       MAX(TRANSACTION_DATE) AS LAST_TRADING_DATE,
       SUM(GROSS_SALES_AMOUNT) AS GROSS_SALES,
       SUM(DISCOUNT_AMOUNT) AS DISCOUNT,
       SUM(GROSS_SALES_AMOUNT)-SUM(DISCOUNT_AMOUNT) AS NET_SALES,
       SUM(UNITS) AS UNITS, COUNT(DISTINCT TRANSACTION_ID) AS TRANSACTIONCOUNT
FROM RETAIL_DWH.MART_SALES.FCT_SALES;

SELECT DEPARTMENT_ID, DEPARTMENT_NAME, CLASS_ID, CLASS_NAME, COUNT(*) AS ITEM_VERSIONS
FROM RETAIL_DWH.MART_SALES.DIM_ITEM GROUP BY 1,2,3,4 ORDER BY 1,3;

SELECT REGION, DISTRICT_NAME, LOCATION_TYPE, COUNT(DISTINCT LOCATION_ID) AS LOCATIONS
FROM RETAIL_DWH.MART_SALES.DIM_LOCATION GROUP BY 1,2,3 ORDER BY 1,2,3;

SELECT d.QUARTER_LABEL, SUM(f.NET_SALES_AMOUNT) AS NET_SALES,
       COUNT(DISTINCT f.TRANSACTION_ID) AS TRANSACTIONCOUNT
FROM RETAIL_DWH.MART_SALES.FCT_SALES f
JOIN RETAIL_DWH.MART_SALES.DIM_DATE d ON d.DATE_KEY=f.DATE_KEY
GROUP BY d.QUARTER_KEY,d.QUARTER_LABEL ORDER BY d.QUARTER_KEY;

SELECT CALENDAR_DATE, ISO_WEEK_YEAR, ISO_WEEK_NUMBER, ISO_DAY_OF_WEEK,
       PY_COMPARABLE_DATE
FROM RETAIL_DWH.MART_SALES.DIM_DATE
WHERE CALENDAR_DATE IN ('2026-01-01','2026-12-31');

-- Head-to-head selected Q4 through the agreed demo cutoff. PY uses only
-- the same elapsed current dates mapped to the previous ISO year.
WITH current_dates AS (
    SELECT DATE_KEY, PY_DATE_KEY FROM RETAIL_DWH.MART_SALES.DIM_DATE
    WHERE CALENDAR_DATE BETWEEN '2026-10-01'::DATE AND '2026-11-18'::DATE
), totals AS (
    SELECT
      (SELECT SUM(NET_SALES_AMOUNT) FROM RETAIL_DWH.MART_SALES.FCT_SALES f
       WHERE f.DATE_KEY IN (SELECT DATE_KEY FROM current_dates)) AS CURRENT_NET_SALES,
      (SELECT SUM(NET_SALES_AMOUNT) FROM RETAIL_DWH.MART_SALES.FCT_SALES f
       WHERE f.DATE_KEY IN (SELECT PY_DATE_KEY FROM current_dates)) AS PY_NET_SALES
)
SELECT *, CURRENT_NET_SALES-PY_NET_SALES AS YOY,
       (CURRENT_NET_SALES-PY_NET_SALES)/NULLIF(PY_NET_SALES,0) AS YOY_PCT FROM totals;
