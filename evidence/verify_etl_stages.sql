-- D. FINAL RECONCILIATION: after retail_gold_pipeline or retail_full_etl

-- D1. Same daily sales reconciliation as the DAG; expected all PASS.
-- Includes unparseable-amount failures, not just differences in totals.
WITH dates AS (
    SELECT SOURCE_FILE_DATE AS BUSINESS_DATE FROM RETAIL_DWH.STG.POS_SALES
    UNION SELECT SALE_DATE FROM RETAIL_DWH.TMP.POS_SALES
    UNION SELECT SOURCE_FILE_DATE FROM RETAIL_DWH.DQ.QUARANTINE_RECORDS WHERE SOURCE_TYPE = 'pos_sales'
    UNION SELECT SALE_DATE FROM RETAIL_DWH.TGT.FCT_SALES
), raw_sales AS (
    SELECT SOURCE_FILE_DATE AS BUSINESS_DATE, COUNT(*) AS RAW_ROWS,
           COALESCE(SUM(TRY_TO_DECIMAL(RAW_PAYLOAD:net_sales::VARCHAR, 18, 2)), 0) AS RAW_AMOUNT,
           COUNT_IF(TRY_TO_DECIMAL(RAW_PAYLOAD:net_sales::VARCHAR, 18, 2) IS NULL) AS UNPARSEABLE_RAW_AMOUNTS
    FROM RETAIL_DWH.STG.POS_SALES GROUP BY SOURCE_FILE_DATE
), clean_sales AS (
    SELECT SALE_DATE AS BUSINESS_DATE, COUNT(*) AS ACCEPTED_ROWS,
           COALESCE(SUM(NET_SALES), 0) AS ACCEPTED_AMOUNT
    FROM RETAIL_DWH.TMP.POS_SALES GROUP BY SALE_DATE
), rejected_sales AS (
    SELECT SOURCE_FILE_DATE AS BUSINESS_DATE, COUNT(*) AS REJECTED_ROWS,
           COALESCE(SUM(TRY_TO_DECIMAL(RAW_PAYLOAD:net_sales::VARCHAR, 18, 2)), 0) AS REJECTED_AMOUNT,
           COUNT_IF(TRY_TO_DECIMAL(RAW_PAYLOAD:net_sales::VARCHAR, 18, 2) IS NULL) AS UNPARSEABLE_REJECTED_AMOUNTS
    FROM RETAIL_DWH.DQ.QUARANTINE_RECORDS WHERE SOURCE_TYPE = 'pos_sales'
    GROUP BY SOURCE_FILE_DATE
), gold_sales AS (
    SELECT SALE_DATE AS BUSINESS_DATE, COUNT(*) AS GOLD_ROWS,
           COALESCE(SUM(NET_SALES), 0) AS GOLD_AMOUNT
    FROM RETAIL_DWH.TGT.FCT_SALES GROUP BY SALE_DATE
), compared AS (
    SELECT d.BUSINESS_DATE, COALESCE(r.RAW_ROWS, 0) AS RAW_ROWS,
           COALESCE(c.ACCEPTED_ROWS, 0) AS ACCEPTED_ROWS,
           COALESCE(q.REJECTED_ROWS, 0) AS REJECTED_ROWS,
           COALESCE(g.GOLD_ROWS, 0) AS GOLD_ROWS,
           COALESCE(r.RAW_AMOUNT, 0) AS RAW_AMOUNT,
           COALESCE(c.ACCEPTED_AMOUNT, 0) AS ACCEPTED_AMOUNT,
           COALESCE(q.REJECTED_AMOUNT, 0) AS REJECTED_AMOUNT,
           COALESCE(g.GOLD_AMOUNT, 0) AS GOLD_AMOUNT,
           COALESCE(r.UNPARSEABLE_RAW_AMOUNTS, 0) AS UNPARSEABLE_RAW_AMOUNTS,
           COALESCE(q.UNPARSEABLE_REJECTED_AMOUNTS, 0) AS UNPARSEABLE_REJECTED_AMOUNTS
    FROM dates d LEFT JOIN raw_sales r ON r.BUSINESS_DATE = d.BUSINESS_DATE
    LEFT JOIN clean_sales c ON c.BUSINESS_DATE = d.BUSINESS_DATE
    LEFT JOIN rejected_sales q ON q.BUSINESS_DATE = d.BUSINESS_DATE
    LEFT JOIN gold_sales g ON g.BUSINESS_DATE = d.BUSINESS_DATE
)
SELECT *, IFF(RAW_ROWS > 0 AND UNPARSEABLE_RAW_AMOUNTS = 0
    AND UNPARSEABLE_REJECTED_AMOUNTS = 0
    AND RAW_ROWS = ACCEPTED_ROWS + REJECTED_ROWS AND GOLD_ROWS = ACCEPTED_ROWS
    AND ABS(RAW_AMOUNT - ACCEPTED_AMOUNT - REJECTED_AMOUNT) <= 0.005
    AND ABS(GOLD_AMOUNT - ACCEPTED_AMOUNT) <= 0.005, 'PASS', 'FAIL') AS STATUS
FROM compared ORDER BY BUSINESS_DATE;

-- D2. Same 13 Gold integrity checks as the DAG. All FAILURES must be zero.
-- Empty tables can yield zero failures: also inspect C1 and D1 for coverage.
WITH item_ordered AS (
    SELECT ITEM_ID, EFFECTIVE_FROM,
           LAG(COALESCE(EFFECTIVE_TO, '9999-12-31'::DATE)) OVER (
               PARTITION BY ITEM_ID ORDER BY EFFECTIVE_FROM) AS PREVIOUS_END
    FROM RETAIL_DWH.TGT.DIM_ITEM
), locn_ordered AS (
    SELECT STORE_ID, EFFECTIVE_FROM,
           LAG(COALESCE(EFFECTIVE_TO, '9999-12-31'::DATE)) OVER (
               PARTITION BY STORE_ID ORDER BY EFFECTIVE_FROM) AS PREVIOUS_END
    FROM RETAIL_DWH.TGT.DIM_LOCN
), inv_ordered AS (
    SELECT STORE_ID, ITEM_ID, EFFECTIVE_FROM,
           LAG(COALESCE(EFFECTIVE_TO, '9999-12-31'::DATE)) OVER (
               PARTITION BY STORE_ID, ITEM_ID ORDER BY EFFECTIVE_FROM) AS PREVIOUS_END
    FROM RETAIL_DWH.TGT.FCT_INVENTORY
), checks AS (
    SELECT 'DIM_ITEM_OVERLAP' AS CHECK_NAME, COUNT(*) AS FAILURES FROM item_ordered WHERE PREVIOUS_END > EFFECTIVE_FROM
    UNION ALL SELECT 'DIM_LOCN_OVERLAP', COUNT(*) FROM locn_ordered WHERE PREVIOUS_END > EFFECTIVE_FROM
    UNION ALL SELECT 'INVENTORY_OVERLAP', COUNT(*) FROM inv_ordered WHERE PREVIOUS_END > EFFECTIVE_FROM
    UNION ALL SELECT 'ITEM_CURRENT_COUNT', COUNT(*) FROM (
        SELECT ITEM_ID FROM RETAIL_DWH.TGT.DIM_ITEM GROUP BY ITEM_ID HAVING COUNT_IF(IS_CURRENT) <> 1)
    UNION ALL SELECT 'LOCN_CURRENT_COUNT', COUNT(*) FROM (
        SELECT STORE_ID FROM RETAIL_DWH.TGT.DIM_LOCN GROUP BY STORE_ID HAVING COUNT_IF(IS_CURRENT) <> 1)
    UNION ALL SELECT 'INVENTORY_CURRENT_COUNT', COUNT(*) FROM (
        SELECT STORE_ID, ITEM_ID FROM RETAIL_DWH.TGT.FCT_INVENTORY GROUP BY STORE_ID, ITEM_ID HAVING COUNT_IF(IS_CURRENT) <> 1)
    UNION ALL SELECT 'SALES_BUSINESS_KEY_DUPLICATES', COUNT(*) FROM (
        SELECT TRANSACTION_ID, LINE_NUMBER FROM RETAIL_DWH.TGT.FCT_SALES GROUP BY TRANSACTION_ID, LINE_NUMBER HAVING COUNT(*) > 1)
    UNION ALL SELECT 'INVENTORY_START_DUPLICATES', COUNT(*) FROM (
        SELECT STORE_ID, ITEM_ID, EFFECTIVE_FROM FROM RETAIL_DWH.TGT.FCT_INVENTORY GROUP BY STORE_ID, ITEM_ID, EFFECTIVE_FROM HAVING COUNT(*) > 1)
    UNION ALL SELECT 'SALES_INVALID_HISTORICAL_KEYS', COUNT(*)
    FROM RETAIL_DWH.TGT.FCT_SALES f
    LEFT JOIN RETAIL_DWH.TGT.DIM_ITEM i ON f.ITEM_SK = i.ITEM_SK AND f.ITEM_ID = i.ITEM_ID
      AND i.EFFECTIVE_FROM <= f.SALE_DATE AND (f.SALE_DATE < i.EFFECTIVE_TO OR i.EFFECTIVE_TO IS NULL)
    LEFT JOIN RETAIL_DWH.TGT.DIM_LOCN l ON f.LOCN_SK = l.LOCN_SK AND f.STORE_ID = l.STORE_ID
      AND l.EFFECTIVE_FROM <= f.SALE_DATE AND (f.SALE_DATE < l.EFFECTIVE_TO OR l.EFFECTIVE_TO IS NULL)
    WHERE i.ITEM_SK IS NULL OR l.LOCN_SK IS NULL
    UNION ALL SELECT 'INVENTORY_INVALID_HISTORICAL_KEYS', COUNT(*)
    FROM RETAIL_DWH.TGT.FCT_INVENTORY f
    LEFT JOIN RETAIL_DWH.TGT.DIM_ITEM i ON f.ITEM_SK = i.ITEM_SK AND f.ITEM_ID = i.ITEM_ID
      AND i.EFFECTIVE_FROM <= f.EFFECTIVE_FROM AND (f.EFFECTIVE_FROM < i.EFFECTIVE_TO OR i.EFFECTIVE_TO IS NULL)
    LEFT JOIN RETAIL_DWH.TGT.DIM_LOCN l ON f.LOCN_SK = l.LOCN_SK AND f.STORE_ID = l.STORE_ID
      AND l.EFFECTIVE_FROM <= f.EFFECTIVE_FROM AND (f.EFFECTIVE_FROM < l.EFFECTIVE_TO OR l.EFFECTIVE_TO IS NULL)
    WHERE i.ITEM_SK IS NULL OR l.LOCN_SK IS NULL
    UNION ALL SELECT 'MISSING_OR_WRONG_INVENTORY_OBSERVATIONS', COUNT(*)
    FROM RETAIL_DWH.TMP.INVENTORY_SNAPSHOT s
    LEFT JOIN RETAIL_DWH.TGT.DIM_ITEM i ON i.ITEM_ID = s.ITEM_ID
      AND i.EFFECTIVE_FROM <= s.SNAPSHOT_DATE AND (s.SNAPSHOT_DATE < i.EFFECTIVE_TO OR i.EFFECTIVE_TO IS NULL)
    LEFT JOIN RETAIL_DWH.TGT.DIM_LOCN l ON l.STORE_ID = s.STORE_ID
      AND l.EFFECTIVE_FROM <= s.SNAPSHOT_DATE AND (s.SNAPSHOT_DATE < l.EFFECTIVE_TO OR l.EFFECTIVE_TO IS NULL)
    LEFT JOIN RETAIL_DWH.TGT.FCT_INVENTORY f ON f.ITEM_ID = s.ITEM_ID AND f.STORE_ID = s.STORE_ID
      AND f.ITEM_SK = i.ITEM_SK AND f.LOCN_SK = l.LOCN_SK
      AND f.EFFECTIVE_FROM <= s.SNAPSHOT_DATE AND (s.SNAPSHOT_DATE < f.EFFECTIVE_TO OR f.EFFECTIVE_TO IS NULL)
      AND f.QUANTITY_ON_HAND = s.QUANTITY_ON_HAND AND f.UNIT_COST = s.UNIT_COST AND f.INVENTORY_VALUE = s.INVENTORY_VALUE
    WHERE f.INVENTORY_VERSION_SK IS NULL
    UNION ALL SELECT 'MISSING_OR_MISMATCHED_SALES_LINES', COUNT(*)
    FROM RETAIL_DWH.TMP.POS_SALES s LEFT JOIN RETAIL_DWH.TGT.FCT_SALES f
      ON f.TRANSACTION_ID = s.TRANSACTION_ID AND f.LINE_NUMBER = s.LINE_NUMBER
      AND f.STORE_ID = s.STORE_ID AND f.ITEM_ID = s.ITEM_ID AND f.SALE_DATE = s.SALE_DATE
      AND f.QUANTITY = s.QUANTITY AND f.UNIT_PRICE = s.UNIT_PRICE
      AND f.DISCOUNT_AMOUNT = s.DISCOUNT_AMOUNT AND f.NET_SALES = s.NET_SALES AND f.SOURCE_ROW_ID = s.SOURCE_ROW_ID
    WHERE f.SALES_LINE_SK IS NULL
    UNION ALL SELECT 'QUARANTINED_SALES_PUBLISHED', COUNT(*)
    FROM RETAIL_DWH.TGT.FCT_SALES f JOIN RETAIL_DWH.DQ.QUARANTINE_RECORDS q
      ON q.SOURCE_ROW_ID = f.SOURCE_ROW_ID AND q.SOURCE_TYPE = 'pos_sales'
)
SELECT *, IFF(FAILURES = 0, 'PASS', 'FAIL') AS STATUS FROM checks ORDER BY CHECK_NAME;

