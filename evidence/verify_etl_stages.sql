-- C3. SCD1: latest SC03 description should match its latest accepted snapshot,
-- with exactly one Gold row. A before/after screenshot is needed to prove
-- an in-place update and stable SUBCLASS_SK, not just the final state.
WITH latest AS (
    SELECT SUBCLASS_ID, SUBCLASS_NAME, SNAPSHOT_DATE
    FROM RETAIL_DWH.TMP.ITEM_MASTER WHERE SUBCLASS_ID = 'SC03'
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY SUBCLASS_ID ORDER BY SNAPSHOT_DATE DESC,
        SOURCE_FILE_NAME DESC, SOURCE_ROW_NUMBER DESC, SOURCE_ROW_ID DESC
    ) = 1
)
SELECT s.SUBCLASS_ID, s.SNAPSHOT_DATE AS LATEST_SNAPSHOT_DATE,
       s.SUBCLASS_NAME AS EXPECTED_NAME, t.SUBCLASS_NAME AS GOLD_NAME,
       t.SUBCLASS_SK, t.UPDATED_AT,
       IFF(t.SUBCLASS_NAME = s.SUBCLASS_NAME
           AND COUNT(t.SUBCLASS_SK) OVER (PARTITION BY s.SUBCLASS_ID) = 1,
           'PASS', 'FAIL') AS STATUS
FROM latest s LEFT JOIN RETAIL_DWH.TGT.DIM_SUBCLASS t ON t.SUBCLASS_ID = s.SUBCLASS_ID;

