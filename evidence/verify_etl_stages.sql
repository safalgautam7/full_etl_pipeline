-- A. STG / BRONZE: after retail_stg_ingestion

-- A1. Physical row identity. Expected fixture counts: 150, 60, 150, 150.
-- Every row should show PASS; raw business defects must still be retained.
WITH counts AS (
    SELECT 'ITEM_MASTER' AS SOURCE, COUNT(*) AS RAW_ROWS,
           COUNT(DISTINCT SOURCE_ROW_ID) AS UNIQUE_ROW_IDS,
           COUNT_IF(SOURCE_ROW_ID IS NULL OR SOURCE_FILE_ID IS NULL
                    OR RAW_PAYLOAD IS NULL) AS INVALID_METADATA
    FROM RETAIL_DWH.STG.ITEM_MASTER
    UNION ALL
    SELECT 'STORE_MASTER', COUNT(*), COUNT(DISTINCT SOURCE_ROW_ID),
           COUNT_IF(SOURCE_ROW_ID IS NULL OR SOURCE_FILE_ID IS NULL OR RAW_PAYLOAD IS NULL)
    FROM RETAIL_DWH.STG.STORE_MASTER
    UNION ALL
    SELECT 'POS_SALES', COUNT(*), COUNT(DISTINCT SOURCE_ROW_ID),
           COUNT_IF(SOURCE_ROW_ID IS NULL OR SOURCE_FILE_ID IS NULL OR RAW_PAYLOAD IS NULL)
    FROM RETAIL_DWH.STG.POS_SALES
    UNION ALL
    SELECT 'INVENTORY_SNAPSHOT', COUNT(*), COUNT(DISTINCT SOURCE_ROW_ID),
           COUNT_IF(SOURCE_ROW_ID IS NULL OR SOURCE_FILE_ID IS NULL OR RAW_PAYLOAD IS NULL)
    FROM RETAIL_DWH.STG.INVENTORY_SNAPSHOT
)
SELECT *, IFF(RAW_ROWS > 0 AND RAW_ROWS = UNIQUE_ROW_IDS
              AND COALESCE(INVALID_METADATA, 0) = 0, 'PASS', 'FAIL') AS STATUS
FROM counts ORDER BY SOURCE;

-- A2. File manifest versus physical STG rows, including unregistered files.
-- Expected fixture: 17 rows, 30 rows per file, all LOADED and PASS.
-- Duplicate manifest identities also cause FAIL.
WITH raw_rows AS (
    SELECT 'item_master' AS SOURCE_TYPE, SOURCE_FILE_ID, SOURCE_FILE_NAME
    FROM RETAIL_DWH.STG.ITEM_MASTER
    UNION ALL SELECT 'store_master', SOURCE_FILE_ID, SOURCE_FILE_NAME
    FROM RETAIL_DWH.STG.STORE_MASTER
    UNION ALL SELECT 'pos_sales', SOURCE_FILE_ID, SOURCE_FILE_NAME
    FROM RETAIL_DWH.STG.POS_SALES
    UNION ALL SELECT 'inventory_snapshot', SOURCE_FILE_ID, SOURCE_FILE_NAME
    FROM RETAIL_DWH.STG.INVENTORY_SNAPSHOT
), actual AS (
    SELECT SOURCE_TYPE, SOURCE_FILE_ID, SOURCE_FILE_NAME, COUNT(*) AS STG_ROWS
    FROM raw_rows GROUP BY SOURCE_TYPE, SOURCE_FILE_ID, SOURCE_FILE_NAME
), manifest AS (
    SELECT *, COUNT(*) OVER (PARTITION BY SOURCE_FILE_NAME) AS NAME_OCCURRENCES,
              COUNT(*) OVER (PARTITION BY SOURCE_FILE_ID) AS ID_OCCURRENCES
    FROM RETAIL_DWH.CONTROL.FILE_MANIFEST
)
SELECT COALESCE(m.SOURCE_FILE_NAME, a.SOURCE_FILE_NAME) AS SOURCE_FILE_NAME,
       COALESCE(m.SOURCE_TYPE, a.SOURCE_TYPE) AS SOURCE_TYPE,
       m.SOURCE_FILE_SHA256, m.LOAD_STATUS, m.ROW_COUNT AS MANIFEST_ROWS,
       COALESCE(a.STG_ROWS, 0) AS STG_ROWS, m.BATCH_ID, m.LOADED_AT,
       IFF(m.LOAD_STATUS = 'LOADED' AND m.ROW_COUNT = a.STG_ROWS
           AND m.NAME_OCCURRENCES = 1 AND m.ID_OCCURRENCES = 1
           AND LENGTH(m.SOURCE_FILE_SHA256) = 64, 'PASS', 'FAIL') AS STATUS
FROM manifest m FULL OUTER JOIN actual a
  ON m.SOURCE_FILE_ID = a.SOURCE_FILE_ID
 AND m.SOURCE_FILE_NAME = a.SOURCE_FILE_NAME AND m.SOURCE_TYPE = a.SOURCE_TYPE
ORDER BY SOURCE_FILE_NAME;

-- A3. Fixture example: raw defects are preserved, not discarded at ingestion.
-- Expected: 2 blank item IDs and 1 negative quantity on 2026-11-11.
SELECT SOURCE_FILE_DATE, COUNT(*) AS RAW_SALES_ROWS,
       COUNT_IF(NULLIF(TRIM(RAW_PAYLOAD:item_id::VARCHAR), '') IS NULL) AS MISSING_ITEM_IDS,
       COUNT_IF(TRY_TO_NUMBER(RAW_PAYLOAD:quantity::VARCHAR) < 0) AS NEGATIVE_QUANTITIES
FROM RETAIL_DWH.STG.POS_SALES
GROUP BY SOURCE_FILE_DATE ORDER BY SOURCE_FILE_DATE;

-- B. TMP / SILVER AND DQ: after retail_tmp_processing

-- B1. Exact disposition coverage for EVERY source row, not just matching totals.
-- PASS means each raw identity appears exactly once in TMP or DQ, never both;
-- no extra published identity or duplicate raw identity is allowed.
-- Fixture totals: raw 510 = accepted 505 + rejected 5.
WITH raw_rows AS (
    SELECT 'item_master' AS SOURCE, SOURCE_ROW_ID FROM RETAIL_DWH.STG.ITEM_MASTER
    UNION ALL SELECT 'store_master', SOURCE_ROW_ID FROM RETAIL_DWH.STG.STORE_MASTER
    UNION ALL SELECT 'pos_sales', SOURCE_ROW_ID FROM RETAIL_DWH.STG.POS_SALES
    UNION ALL SELECT 'inventory_snapshot', SOURCE_ROW_ID FROM RETAIL_DWH.STG.INVENTORY_SNAPSHOT
), decisions AS (
    SELECT 'item_master' AS SOURCE, SOURCE_ROW_ID, 'ACCEPTED' AS DISPOSITION FROM RETAIL_DWH.TMP.ITEM_MASTER
    UNION ALL SELECT 'store_master', SOURCE_ROW_ID, 'ACCEPTED' FROM RETAIL_DWH.TMP.STORE_MASTER
    UNION ALL SELECT 'pos_sales', SOURCE_ROW_ID, 'ACCEPTED' FROM RETAIL_DWH.TMP.POS_SALES
    UNION ALL SELECT 'inventory_snapshot', SOURCE_ROW_ID, 'ACCEPTED' FROM RETAIL_DWH.TMP.INVENTORY_SNAPSHOT
    UNION ALL SELECT SOURCE_TYPE, SOURCE_ROW_ID, 'REJECTED' FROM RETAIL_DWH.DQ.QUARANTINE_RECORDS
), r AS (
    SELECT SOURCE, SOURCE_ROW_ID, COUNT(*) AS RAW_COUNT
    FROM raw_rows GROUP BY SOURCE, SOURCE_ROW_ID
), d AS (
    SELECT SOURCE, SOURCE_ROW_ID,
           COUNT_IF(DISPOSITION = 'ACCEPTED') AS ACCEPTED_COUNT,
           COUNT_IF(DISPOSITION = 'REJECTED') AS REJECTED_COUNT
    FROM decisions GROUP BY SOURCE, SOURCE_ROW_ID
), totals AS (
    SELECT COALESCE(r.SOURCE, d.SOURCE) AS SOURCE,
           SUM(COALESCE(r.RAW_COUNT, 0)) AS RAW_ROWS,
           SUM(COALESCE(d.ACCEPTED_COUNT, 0)) AS ACCEPTED_ROWS,
           SUM(COALESCE(d.REJECTED_COUNT, 0)) AS REJECTED_ROWS,
           COUNT_IF(COALESCE(r.RAW_COUNT, 0) <> 1
               OR COALESCE(d.ACCEPTED_COUNT, 0) + COALESCE(d.REJECTED_COUNT, 0) <> 1
               OR COALESCE(r.SOURCE_ROW_ID, d.SOURCE_ROW_ID) IS NULL) AS BAD_IDENTITIES
    FROM r FULL OUTER JOIN d ON r.SOURCE = d.SOURCE AND r.SOURCE_ROW_ID = d.SOURCE_ROW_ID
    GROUP BY COALESCE(r.SOURCE, d.SOURCE)
)
SELECT *, IFF(RAW_ROWS > 0 AND RAW_ROWS = ACCEPTED_ROWS + REJECTED_ROWS
              AND COALESCE(BAD_IDENTITIES, 0) = 0, 'PASS', 'FAIL') AS STATUS
FROM totals ORDER BY SOURCE;

