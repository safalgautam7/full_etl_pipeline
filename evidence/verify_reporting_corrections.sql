-- Read-only checks after the migration and standalone Gold bootstrap.
-- All check_reporting_integrity.sql failure counts must also be zero.
SELECT MIN(CALENDAR_DATE) AS FIRST_DATE, MAX(CALENDAR_DATE) AS LAST_DATE,
       COUNT(*) AS CALENDAR_DAYS, COUNT(DISTINCT DATE_KEY) AS UNIQUE_KEYS
FROM RETAIL_DWH.TGT.DIM_DATE;

SELECT CALENDAR_DATE, MONTH_NAME, ISO_DAY_OF_WEEK, DAY_NAME,
       ISO_WEEK_NUMBER, ISO_WEEK_YEAR
FROM RETAIL_DWH.TGT.DIM_DATE
WHERE CALENDAR_DATE IN ('2024-02-29', '2026-12-31', '2027-01-01');

SELECT SNAPSHOT_DATE, COUNT(*) AS POSITIONS, SUM(QUANTITY_ON_HAND) AS UNITS,
       SUM(INVENTORY_VALUE) AS STOCK_VALUE
FROM RETAIL_DWH.TGT.FCT_INVENTORY_DAILY
GROUP BY SNAPSHOT_DATE ORDER BY SNAPSHOT_DATE;

SELECT (SELECT COUNT(*) FROM RETAIL_DWH.TMP.INVENTORY_SNAPSHOT) AS ACCEPTED_OBSERVATIONS,
       (SELECT COUNT(*) FROM RETAIL_DWH.TGT.FCT_INVENTORY_DAILY) AS DAILY_POSITIONS;

SELECT CORRECTION_ID, SOURCE_FILE_NAME, OLD_FILE_ID, NEW_FILE_ID, REASON,
       APPROVED_BY, STATUS, STARTED_AT, FINISHED_AT, ERROR_DETAIL
FROM RETAIL_DWH.CONTROL.CORRECTION_RUNS ORDER BY STARTED_AT DESC;

-- Copy the current SHA into expected_old_sha256 when approving a correction.
SELECT SOURCE_FILE_NAME, SOURCE_FILE_SHA256, SOURCE_FILE_ID, ROW_COUNT
FROM RETAIL_DWH.CONTROL.FILE_MANIFEST ORDER BY SOURCE_FILE_DATE, SOURCE_FILE_NAME;

SELECT CORRECTION_ID, SOURCE_TYPE, SOURCE_FILE_ID, COUNT(*) AS ARCHIVED_ROWS
FROM RETAIL_DWH.CONTROL.RAW_VERSION_ARCHIVE
GROUP BY CORRECTION_ID, SOURCE_TYPE, SOURCE_FILE_ID;
