--Stage 7 | Create two Gold fact tables.
-- Run in Snowflake once before triggering retail_gold_pipeline.
-- Safe to repeat; do not CREATE OR REPLACE populated Gold tables.
USE ROLE SYSADMIN;
USE WAREHOUSE SNOWFLAKE_LEARNING_WH;

CREATE TABLE IF NOT EXISTS RETAIL_DWH.TGT.FCT_SALES (
    SALES_LINE_SK NUMBER(38,0) IDENTITY(1,1),
    TRANSACTION_ID VARCHAR(100) NOT NULL,
    LINE_NUMBER NUMBER(38,0) NOT NULL,
    STORE_ID VARCHAR(50) NOT NULL,
    ITEM_ID VARCHAR(50) NOT NULL,
    SALE_DATE DATE NOT NULL,
    ITEM_SK NUMBER(38,0) NOT NULL,
    LOCN_SK NUMBER(38,0) NOT NULL,
    QUANTITY NUMBER(38,0) NOT NULL,
    UNIT_PRICE NUMBER(18,2) NOT NULL,
    DISCOUNT_AMOUNT NUMBER(18,2) NOT NULL,
    NET_SALES NUMBER(18,2) NOT NULL,
    SOURCE_ROW_ID VARCHAR(64) NOT NULL,
    REC_UPDT_TS TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS RETAIL_DWH.TGT.FCT_INVENTORY (
    INVENTORY_VERSION_SK NUMBER(38,0) IDENTITY(1,1),
    STORE_ID VARCHAR(50) NOT NULL,
    ITEM_ID VARCHAR(50) NOT NULL,
    ITEM_SK NUMBER(38,0) NOT NULL,
    LOCN_SK NUMBER(38,0) NOT NULL,
    QUANTITY_ON_HAND NUMBER(38,0) NOT NULL,
    UNIT_COST NUMBER(18,2) NOT NULL,
    INVENTORY_VALUE NUMBER(18,2) NOT NULL,
    EFFECTIVE_FROM DATE NOT NULL,
    EFFECTIVE_TO DATE,
    IS_CURRENT BOOLEAN NOT NULL,
    SOURCE_ROW_ID VARCHAR(64) NOT NULL,
    REC_UPDT_TS TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP()
);

-- These are conceptual primary/foreign keys. Snowflake standard tables
-- do not enforce their uniqueness/referential integrity; tests must.
