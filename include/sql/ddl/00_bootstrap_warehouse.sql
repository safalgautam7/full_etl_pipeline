-- MANUAL fresh-install bootstrap. Review role/warehouse before running.
-- Names match the checked-in SQL/config. IF NOT EXISTS never replaces data.
-- Creating/resuming a warehouse can incur Snowflake charges.
USE ROLE SYSADMIN;

CREATE WAREHOUSE IF NOT EXISTS SNOWFLAKE_LEARNING_WH
    WAREHOUSE_SIZE = 'XSMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE;
USE WAREHOUSE SNOWFLAKE_LEARNING_WH;

CREATE DATABASE IF NOT EXISTS RETAIL_DWH;
CREATE SCHEMA IF NOT EXISTS RETAIL_DWH.STG;
CREATE SCHEMA IF NOT EXISTS RETAIL_DWH.TMP;
CREATE SCHEMA IF NOT EXISTS RETAIL_DWH.DQ;
CREATE SCHEMA IF NOT EXISTS RETAIL_DWH.TGT;
CREATE SCHEMA IF NOT EXISTS RETAIL_DWH.CONTROL;

-- Named internal stage: stores both original CSVs and generated JSONL.
-- COPY specifies its JSON format explicitly at runtime.
CREATE STAGE IF NOT EXISTS RETAIL_DWH.STG.CSV_LANDING;

-- Bronze is a raw envelope, not a typed business schema. All four raw sources
-- share this shape; business columns stay inside RAW_PAYLOAD until Silver.
CREATE TABLE IF NOT EXISTS RETAIL_DWH.STG.ITEM_MASTER (
    SOURCE_ROW_ID VARCHAR(64) NOT NULL,
    SOURCE_FILE_ID VARCHAR(64) NOT NULL,
    SOURCE_FILE_NAME VARCHAR(255) NOT NULL,
    SOURCE_FILE_DATE DATE NOT NULL,
    SOURCE_ROW_NUMBER NUMBER(38,0) NOT NULL,
    RAW_PAYLOAD VARIANT NOT NULL,
    BATCH_ID VARCHAR(100) NOT NULL,
    INGESTED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP()
);
CREATE TABLE IF NOT EXISTS RETAIL_DWH.STG.STORE_MASTER
    LIKE RETAIL_DWH.STG.ITEM_MASTER;
CREATE TABLE IF NOT EXISTS RETAIL_DWH.STG.POS_SALES
    LIKE RETAIL_DWH.STG.ITEM_MASTER;
CREATE TABLE IF NOT EXISTS RETAIL_DWH.STG.INVENTORY_SNAPSHOT
    LIKE RETAIL_DWH.STG.ITEM_MASTER;

