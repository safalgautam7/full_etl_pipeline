-- Purpose-specific star contract. No sales copies or independent loading job.
-- Execute after the attribute migration. All fact dates are transaction dates.
CREATE SCHEMA IF NOT EXISTS RETAIL_DWH.MART_SALES;

CREATE OR REPLACE VIEW RETAIL_DWH.MART_SALES.DIM_DATE AS
SELECT d.DATE_KEY, d.CALENDAR_DATE, d.CALENDAR_YEAR,
       d.QUARTER_NUMBER, d.CALENDAR_YEAR * 10 + d.QUARTER_NUMBER AS QUARTER_KEY,
       TO_VARCHAR(d.CALENDAR_YEAR) || ' Q' || TO_VARCHAR(d.QUARTER_NUMBER) AS QUARTER_LABEL,
       DATE_TRUNC('QUARTER', d.CALENDAR_DATE)::DATE AS QUARTER_START_DATE,
       LAST_DAY(d.CALENDAR_DATE, 'QUARTER') AS QUARTER_END_DATE,
       d.MONTH_NUMBER, d.MONTH_NAME, d.YEAR_MONTH_KEY,
       TO_CHAR(d.CALENDAR_DATE, 'YYYY-MM') AS YEAR_MONTH_LABEL,
       d.MONTH_START_DATE, d.MONTH_END_DATE, d.DAY_OF_MONTH,
       d.ISO_WEEK_YEAR, d.ISO_WEEK_NUMBER, d.ISO_DAY_OF_WEEK, d.DAY_NAME,
       d.ISO_WEEK_YEAR * 100 + d.ISO_WEEK_NUMBER AS ISO_WEEK_KEY,
       'W' || LPAD(TO_VARCHAR(d.ISO_WEEK_NUMBER), 2, '0') AS ISO_WEEK_LABEL,
       DATEADD('DAY', 1 - d.ISO_DAY_OF_WEEK, d.CALENDAR_DATE)::DATE AS WEEK_START_DATE,
       DATEADD('DAY', 7 - d.ISO_DAY_OF_WEEK, d.CALENDAR_DATE)::DATE AS WEEK_END_DATE,
       py.CALENDAR_DATE AS PY_COMPARABLE_DATE, py.DATE_KEY AS PY_DATE_KEY
FROM RETAIL_DWH.TGT.DIM_DATE d
LEFT JOIN RETAIL_DWH.TGT.DIM_DATE py
  ON py.ISO_WEEK_YEAR = d.ISO_WEEK_YEAR - 1
 AND py.ISO_WEEK_NUMBER = d.ISO_WEEK_NUMBER
 AND py.ISO_DAY_OF_WEEK = d.ISO_DAY_OF_WEEK;
-- Week 53 with no previous-ISO-year counterpart intentionally returns NULL.

CREATE OR REPLACE VIEW RETAIL_DWH.MART_SALES.DIM_ITEM AS
SELECT i.ITEM_SK, i.ITEM_ID, i.ITEM_NAME, i.BRAND, i.UNIT_OF_MEASURE,
       i.DEPARTMENT_ID, i.DEPARTMENT_NAME, i.CLASS_ID, i.CLASS_NAME,
       i.SUBCLASS_ID, s.SUBCLASS_NAME, i.LIST_PRICE, i.IS_ACTIVE,
       i.EFFECTIVE_FROM, i.EFFECTIVE_TO, i.IS_CURRENT
FROM RETAIL_DWH.TGT.DIM_ITEM i
LEFT JOIN RETAIL_DWH.TGT.DIM_SUBCLASS s ON s.SUBCLASS_SK = i.SUBCLASS_SK;

CREATE OR REPLACE VIEW RETAIL_DWH.MART_SALES.DIM_LOCATION AS
SELECT l.LOCN_SK AS LOCATION_SK, l.STORE_ID AS LOCATION_ID,
       l.STORE_NAME AS LOCATION_NAME, l.CITY, l.REGION,
       l.DISTRICT_ID, d.DISTRICT_NAME, l.LOCATION_TYPE,
       l.IS_ACTIVE, l.EFFECTIVE_FROM, l.EFFECTIVE_TO, l.IS_CURRENT
FROM RETAIL_DWH.TGT.DIM_LOCN l
LEFT JOIN RETAIL_DWH.TGT.DIM_DISTRICT d ON d.DISTRICT_SK = l.DISTRICT_SK;

CREATE OR REPLACE VIEW RETAIL_DWH.MART_SALES.FCT_SALES AS
SELECT SALES_LINE_SK, TRANSACTION_ID, LINE_NUMBER,
       SALE_DATE AS TRANSACTION_DATE,
       TO_NUMBER(TO_CHAR(SALE_DATE, 'YYYYMMDD')) AS DATE_KEY,
       ITEM_SK, LOCN_SK AS LOCATION_SK, STORE_ID AS LOCATION_ID,
       QUANTITY AS UNITS, UNIT_PRICE,
       -- Source has no separate gross amount. Reconstruct gross from its
       -- accepted net+discount so the report identity is exact, not tolerance-based.
       NET_SALES + DISCOUNT_AMOUNT AS GROSS_SALES_AMOUNT,
       DISCOUNT_AMOUNT, NET_SALES AS NET_SALES_AMOUNT,
       QUANTITY * UNIT_PRICE AS EXTENDED_PRICE_AMOUNT,
       SOURCE_ROW_ID
FROM RETAIL_DWH.TGT.FCT_SALES;
