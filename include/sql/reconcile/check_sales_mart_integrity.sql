SELECT 'MART_ITEM_KEY_DUPLICATES' AS CHECK_NAME, COUNT(*) AS FAILURES
FROM (SELECT ITEM_SK FROM RETAIL_DWH.MART_SALES.DIM_ITEM GROUP BY ITEM_SK HAVING COUNT(*)<>1)
UNION ALL
SELECT 'MART_LOCATION_KEY_DUPLICATES', COUNT(*)
FROM (SELECT LOCATION_SK FROM RETAIL_DWH.MART_SALES.DIM_LOCATION GROUP BY LOCATION_SK HAVING COUNT(*)<>1)
UNION ALL
SELECT 'MART_UNMAPPED_HIERARCHY', COUNT(*) FROM RETAIL_DWH.MART_SALES.DIM_ITEM
WHERE DEPARTMENT_ID IS NULL OR DEPARTMENT_NAME IS NULL OR CLASS_ID IS NULL OR CLASS_NAME IS NULL
   OR DEPARTMENT_ID='UNMAPPED' OR CLASS_ID='UNMAPPED'
UNION ALL
SELECT 'MART_UNMAPPED_LOCATION_TYPE', COUNT(*) FROM RETAIL_DWH.MART_SALES.DIM_LOCATION
WHERE LOCATION_TYPE IS NULL OR LOCATION_TYPE='UNMAPPED'
UNION ALL
SELECT 'MART_FACT_ORPHANS', COUNT(*) FROM RETAIL_DWH.MART_SALES.FCT_SALES f
WHERE NOT EXISTS (SELECT 1 FROM RETAIL_DWH.MART_SALES.DIM_ITEM i WHERE i.ITEM_SK=f.ITEM_SK)
   OR NOT EXISTS (SELECT 1 FROM RETAIL_DWH.MART_SALES.DIM_LOCATION l WHERE l.LOCATION_SK=f.LOCATION_SK)
   OR NOT EXISTS (SELECT 1 FROM RETAIL_DWH.MART_SALES.DIM_DATE d WHERE d.DATE_KEY=f.DATE_KEY)
UNION ALL
SELECT 'MART_GROSS_NET_IDENTITY', COUNT(*) FROM RETAIL_DWH.MART_SALES.FCT_SALES
WHERE GROSS_SALES_AMOUNT-DISCOUNT_AMOUNT<>NET_SALES_AMOUNT
UNION ALL
SELECT 'MART_ISO_PY_MISMATCH', COUNT(*) FROM RETAIL_DWH.MART_SALES.DIM_DATE d
WHERE PY_COMPARABLE_DATE IS NOT NULL AND
 (YEAROFWEEKISO(PY_COMPARABLE_DATE)<>ISO_WEEK_YEAR-1
  OR WEEKISO(PY_COMPARABLE_DATE)<>ISO_WEEK_NUMBER
  OR DAYOFWEEKISO(PY_COMPARABLE_DATE)<>ISO_DAY_OF_WEEK)
