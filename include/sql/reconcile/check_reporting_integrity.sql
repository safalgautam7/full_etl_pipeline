-- Every returned count must be zero. Dates use equality, not validity starts.
SELECT 'CALENDAR_DATE_DUPLICATES' AS CHECK_NAME, COUNT(*) AS FAILURES
FROM (SELECT CALENDAR_DATE FROM RETAIL_DWH.TGT.DIM_DATE GROUP BY 1 HAVING COUNT(*) <> 1)
UNION ALL
SELECT 'CALENDAR_KEY_DUPLICATES', COUNT(*)
FROM (SELECT DATE_KEY FROM RETAIL_DWH.TGT.DIM_DATE GROUP BY 1 HAVING COUNT(*) <> 1)
UNION ALL
SELECT 'CALENDAR_INVALID_KEYS', COUNT(*) FROM RETAIL_DWH.TGT.DIM_DATE
WHERE DATE_KEY <> TO_NUMBER(TO_CHAR(CALENDAR_DATE, 'YYYYMMDD'))
UNION ALL
SELECT 'CALENDAR_GAPS', IFF(COUNT(*) = 0, 1,
    DATEDIFF('DAY', MIN(CALENDAR_DATE), MAX(CALENDAR_DATE)) + 1 - COUNT(DISTINCT CALENDAR_DATE))
FROM RETAIL_DWH.TGT.DIM_DATE
UNION ALL
SELECT 'SALES_MISSING_CALENDAR', COUNT(*) FROM RETAIL_DWH.TGT.FCT_SALES f
WHERE NOT EXISTS (SELECT 1 FROM RETAIL_DWH.TGT.DIM_DATE d WHERE d.CALENDAR_DATE=f.SALE_DATE)
UNION ALL
SELECT 'DAILY_INVENTORY_DUPLICATES', COUNT(*) FROM (
    SELECT STORE_ID, ITEM_ID, SNAPSHOT_DATE FROM RETAIL_DWH.TGT.FCT_INVENTORY_DAILY
    GROUP BY 1,2,3 HAVING COUNT(*) <> 1
)
UNION ALL
SELECT 'DAILY_INVENTORY_MISSING_CALENDAR', COUNT(*) FROM RETAIL_DWH.TGT.FCT_INVENTORY_DAILY f
WHERE NOT EXISTS (SELECT 1 FROM RETAIL_DWH.TGT.DIM_DATE d
                  WHERE d.CALENDAR_DATE=f.SNAPSHOT_DATE AND d.DATE_KEY=f.SNAPSHOT_DATE_KEY)
UNION ALL
SELECT 'DAILY_INVENTORY_MISSING_OR_WRONG', COUNT(*)
FROM RETAIL_DWH.TMP.INVENTORY_SNAPSHOT s
LEFT JOIN RETAIL_DWH.TGT.DIM_ITEM i ON i.ITEM_ID=s.ITEM_ID
 AND i.EFFECTIVE_FROM<=s.SNAPSHOT_DATE AND (s.SNAPSHOT_DATE<i.EFFECTIVE_TO OR i.EFFECTIVE_TO IS NULL)
LEFT JOIN RETAIL_DWH.TGT.DIM_LOCN l ON l.STORE_ID=s.STORE_ID
 AND l.EFFECTIVE_FROM<=s.SNAPSHOT_DATE AND (s.SNAPSHOT_DATE<l.EFFECTIVE_TO OR l.EFFECTIVE_TO IS NULL)
LEFT JOIN RETAIL_DWH.TGT.FCT_INVENTORY_DAILY f
 ON f.STORE_ID=s.STORE_ID AND f.ITEM_ID=s.ITEM_ID AND f.SNAPSHOT_DATE=s.SNAPSHOT_DATE
 AND f.ITEM_SK=i.ITEM_SK AND f.LOCN_SK=l.LOCN_SK
 AND f.QUANTITY_ON_HAND=s.QUANTITY_ON_HAND AND f.UNIT_COST=s.UNIT_COST
 AND f.INVENTORY_VALUE=s.INVENTORY_VALUE AND f.SOURCE_ROW_ID=s.SOURCE_ROW_ID
WHERE f.SOURCE_ROW_ID IS NULL
UNION ALL
SELECT 'DAILY_INVENTORY_STALE', COUNT(*) FROM RETAIL_DWH.TGT.FCT_INVENTORY_DAILY f
WHERE NOT EXISTS (SELECT 1 FROM RETAIL_DWH.TMP.INVENTORY_SNAPSHOT s
    WHERE s.STORE_ID=f.STORE_ID AND s.ITEM_ID=f.ITEM_ID AND s.SNAPSHOT_DATE=f.SNAPSHOT_DATE)
