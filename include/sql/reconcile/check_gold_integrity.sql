-- Each query must return 0 failures. Airflow raises if any > 0.
-- Fail on overlap, incomplete observations, wrong historical SKs, etc.
WITH item_ordered AS (
    SELECT ITEM_ID, EFFECTIVE_FROM,
           LAG(COALESCE(EFFECTIVE_TO, '9999-12-31'::DATE)) OVER (
               PARTITION BY ITEM_ID ORDER BY EFFECTIVE_FROM
           ) AS PREVIOUS_END
    FROM RETAIL_DWH.TGT.DIM_ITEM
), locn_ordered AS (
    SELECT STORE_ID, EFFECTIVE_FROM,
           LAG(COALESCE(EFFECTIVE_TO, '9999-12-31'::DATE)) OVER (
               PARTITION BY STORE_ID ORDER BY EFFECTIVE_FROM
           ) AS PREVIOUS_END
    FROM RETAIL_DWH.TGT.DIM_LOCN
), inv_ordered AS (
    SELECT STORE_ID, ITEM_ID, EFFECTIVE_FROM,
           LAG(COALESCE(EFFECTIVE_TO, '9999-12-31'::DATE)) OVER (
               PARTITION BY STORE_ID, ITEM_ID ORDER BY EFFECTIVE_FROM
           ) AS PREVIOUS_END
    FROM RETAIL_DWH.TGT.FCT_INVENTORY
)
SELECT 'DIM_ITEM_OVERLAP' AS CHECK_NAME, COUNT(*) AS FAILURES
FROM item_ordered WHERE PREVIOUS_END > EFFECTIVE_FROM
UNION ALL
SELECT 'DIM_LOCN_OVERLAP', COUNT(*) FROM locn_ordered
WHERE PREVIOUS_END > EFFECTIVE_FROM
UNION ALL
SELECT 'INVENTORY_OVERLAP', COUNT(*) FROM inv_ordered
WHERE PREVIOUS_END > EFFECTIVE_FROM
UNION ALL
SELECT 'ITEM_CURRENT_COUNT', COUNT(*) FROM (
    SELECT ITEM_ID FROM RETAIL_DWH.TGT.DIM_ITEM
    GROUP BY ITEM_ID HAVING COUNT_IF(IS_CURRENT) <> 1
)
UNION ALL
SELECT 'LOCN_CURRENT_COUNT', COUNT(*) FROM (
    SELECT STORE_ID FROM RETAIL_DWH.TGT.DIM_LOCN
    GROUP BY STORE_ID HAVING COUNT_IF(IS_CURRENT) <> 1
)
UNION ALL
SELECT 'INVENTORY_CURRENT_COUNT', COUNT(*) FROM (
    SELECT STORE_ID, ITEM_ID FROM RETAIL_DWH.TGT.FCT_INVENTORY
    GROUP BY STORE_ID, ITEM_ID HAVING COUNT_IF(IS_CURRENT) <> 1
)
UNION ALL
SELECT 'SALES_BUSINESS_KEY_DUPLICATES', COUNT(*) FROM (
    SELECT TRANSACTION_ID, LINE_NUMBER FROM RETAIL_DWH.TGT.FCT_SALES
    GROUP BY TRANSACTION_ID, LINE_NUMBER HAVING COUNT(*) > 1
)
UNION ALL
SELECT 'INVENTORY_START_DUPLICATES', COUNT(*) FROM (
    SELECT STORE_ID, ITEM_ID, EFFECTIVE_FROM
    FROM RETAIL_DWH.TGT.FCT_INVENTORY
    GROUP BY STORE_ID, ITEM_ID, EFFECTIVE_FROM HAVING COUNT(*) > 1
)
UNION ALL
SELECT 'SALES_INVALID_HISTORICAL_KEYS', COUNT(*)
FROM RETAIL_DWH.TGT.FCT_SALES f
LEFT JOIN RETAIL_DWH.TGT.DIM_ITEM i
  ON f.ITEM_SK=i.ITEM_SK AND f.ITEM_ID=i.ITEM_ID
 AND i.EFFECTIVE_FROM<=f.SALE_DATE
 AND (f.SALE_DATE < i.EFFECTIVE_TO OR i.EFFECTIVE_TO IS NULL)
LEFT JOIN RETAIL_DWH.TGT.DIM_LOCN l
  ON f.LOCN_SK=l.LOCN_SK AND f.STORE_ID=l.STORE_ID
 AND l.EFFECTIVE_FROM<=f.SALE_DATE
 AND (f.SALE_DATE < l.EFFECTIVE_TO OR l.EFFECTIVE_TO IS NULL)
WHERE i.ITEM_SK IS NULL OR l.LOCN_SK IS NULL
UNION ALL
SELECT 'INVENTORY_INVALID_HISTORICAL_KEYS', COUNT(*)
FROM RETAIL_DWH.TGT.FCT_INVENTORY f
LEFT JOIN RETAIL_DWH.TGT.DIM_ITEM i
  ON f.ITEM_SK=i.ITEM_SK AND f.ITEM_ID=i.ITEM_ID
 AND i.EFFECTIVE_FROM<=f.EFFECTIVE_FROM
 AND (f.EFFECTIVE_FROM < i.EFFECTIVE_TO OR i.EFFECTIVE_TO IS NULL)
LEFT JOIN RETAIL_DWH.TGT.DIM_LOCN l
  ON f.LOCN_SK=l.LOCN_SK AND f.STORE_ID=l.STORE_ID
 AND l.EFFECTIVE_FROM<=f.EFFECTIVE_FROM
 AND (f.EFFECTIVE_FROM < l.EFFECTIVE_TO OR l.EFFECTIVE_TO IS NULL)
WHERE i.ITEM_SK IS NULL OR l.LOCN_SK IS NULL
UNION ALL
SELECT 'MISSING_OR_WRONG_INVENTORY_OBSERVATIONS', COUNT(*)
FROM RETAIL_DWH.TMP.INVENTORY_SNAPSHOT s
LEFT JOIN RETAIL_DWH.TGT.DIM_ITEM i
  ON i.ITEM_ID=s.ITEM_ID AND i.EFFECTIVE_FROM<=s.SNAPSHOT_DATE
 AND (s.SNAPSHOT_DATE<i.EFFECTIVE_TO OR i.EFFECTIVE_TO IS NULL)
LEFT JOIN RETAIL_DWH.TGT.DIM_LOCN l
  ON l.STORE_ID=s.STORE_ID AND l.EFFECTIVE_FROM<=s.SNAPSHOT_DATE
 AND (s.SNAPSHOT_DATE<l.EFFECTIVE_TO OR l.EFFECTIVE_TO IS NULL)
LEFT JOIN RETAIL_DWH.TGT.FCT_INVENTORY f
  ON f.ITEM_ID=s.ITEM_ID AND f.STORE_ID=s.STORE_ID
 AND f.ITEM_SK=i.ITEM_SK AND f.LOCN_SK=l.LOCN_SK
 AND f.EFFECTIVE_FROM<=s.SNAPSHOT_DATE
 AND (s.SNAPSHOT_DATE<f.EFFECTIVE_TO OR f.EFFECTIVE_TO IS NULL)
 AND f.QUANTITY_ON_HAND=s.QUANTITY_ON_HAND
 AND f.UNIT_COST=s.UNIT_COST
 AND f.INVENTORY_VALUE=s.INVENTORY_VALUE
WHERE f.INVENTORY_VERSION_SK IS NULL
UNION ALL
SELECT 'MISSING_OR_MISMATCHED_SALES_LINES', COUNT(*)
FROM RETAIL_DWH.TMP.POS_SALES s
LEFT JOIN RETAIL_DWH.TGT.FCT_SALES f
 ON f.TRANSACTION_ID=s.TRANSACTION_ID
 AND f.LINE_NUMBER=s.LINE_NUMBER
 AND f.STORE_ID=s.STORE_ID AND f.ITEM_ID=s.ITEM_ID
 AND f.SALE_DATE=s.SALE_DATE AND f.QUANTITY=s.QUANTITY
 AND f.UNIT_PRICE=s.UNIT_PRICE AND f.DISCOUNT_AMOUNT=s.DISCOUNT_AMOUNT
 AND f.NET_SALES=s.NET_SALES AND f.SOURCE_ROW_ID=s.SOURCE_ROW_ID
WHERE f.SALES_LINE_SK IS NULL
UNION ALL
SELECT 'QUARANTINED_SALES_PUBLISHED', COUNT(*)
FROM RETAIL_DWH.TGT.FCT_SALES f
JOIN RETAIL_DWH.DQ.QUARANTINE_RECORDS q
 ON q.SOURCE_ROW_ID=f.SOURCE_ROW_ID AND q.SOURCE_TYPE='pos_sales'
