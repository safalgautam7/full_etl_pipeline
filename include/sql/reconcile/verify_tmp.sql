-- Stage 5 acceptance checks for the 17-file sample dataset.
-- These literals are test expectations only; production DAG never reads them.

-- Expected: ITEM 150, STORE 60, SALES 145, INVENTORY 150.
SELECT 'ITEM_MASTER' AS TABLE_NAME, COUNT(*) AS ACTUAL_ROWS, 150 AS EXPECTED_ROWS
FROM RETAIL_DWH.TMP.ITEM_MASTER
UNION ALL
SELECT 'STORE_MASTER', COUNT(*), 60 FROM RETAIL_DWH.TMP.STORE_MASTER
UNION ALL
SELECT 'POS_SALES', COUNT(*), 145 FROM RETAIL_DWH.TMP.POS_SALES
UNION ALL
SELECT 'INVENTORY_SNAPSHOT', COUNT(*), 150 FROM RETAIL_DWH.TMP.INVENTORY_SNAPSHOT;

-- Expected: 5 rows, 2 NULL_ITEM_ID, 1 each NEGATIVE_QUANTITY,
-- UNKNOWN_ITEM_ID, DUPLICATE_SALES_LINE.
SELECT SOURCE_TYPE, REASON_CODE, COUNT(*) AS REJECTED_ROWS
FROM RETAIL_DWH.DQ.QUARANTINE_RECORDS
GROUP BY SOURCE_TYPE, REASON_CODE
ORDER BY SOURCE_TYPE, REASON_CODE;

-- Expected: Nov 11 = 25, all other days = 30.
SELECT SALE_DATE, COUNT(*) AS ACCEPTED_SALES, SUM(NET_SALES) AS ACCEPTED_AMOUNT
FROM RETAIL_DWH.TMP.POS_SALES
GROUP BY SALE_DATE
ORDER BY SALE_DATE;

-- Expected: 1566.15.
SELECT COUNT(*) AS SALES_COUNT, SUM(NET_SALES) AS SALES_AMOUNT
FROM RETAIL_DWH.TMP.POS_SALES;

-- Expected: zero rows (no repeated physical source identifiers).
SELECT SOURCE_ROW_ID, COUNT(*) AS CNT FROM RETAIL_DWH.TMP.POS_SALES
GROUP BY SOURCE_ROW_ID HAVING COUNT(*) > 1;
SELECT SOURCE_ROW_ID, COUNT(*) AS CNT FROM RETAIL_DWH.DQ.QUARANTINE_RECORDS
GROUP BY SOURCE_ROW_ID HAVING COUNT(*) > 1;

-- Expected: 510 = 505 + 5. SQL works for the current fixture.
SELECT
  (SELECT COUNT(*) FROM RETAIL_DWH.STG.ITEM_MASTER)
    + (SELECT COUNT(*) FROM RETAIL_DWH.STG.STORE_MASTER)
    + (SELECT COUNT(*) FROM RETAIL_DWH.STG.POS_SALES)
    + (SELECT COUNT(*) FROM RETAIL_DWH.STG.INVENTORY_SNAPSHOT) AS STG_COUNT,
  (SELECT COUNT(*) FROM RETAIL_DWH.TMP.ITEM_MASTER)
    + (SELECT COUNT(*) FROM RETAIL_DWH.TMP.STORE_MASTER)
    + (SELECT COUNT(*) FROM RETAIL_DWH.TMP.POS_SALES)
    + (SELECT COUNT(*) FROM RETAIL_DWH.TMP.INVENTORY_SNAPSHOT) AS TMP_COUNT,
  (SELECT COUNT(*) FROM RETAIL_DWH.DQ.QUARANTINE_RECORDS) AS DQ_COUNT;

-- Important: store district change is a valid snapshot update, not quarantine.
-- Expected STORE007 two snapshots on 11/09 and 11/11 (district changes).
SELECT SNAPSHOT_DATE, STORE_ID, DISTRICT_ID
FROM RETAIL_DWH.TMP.STORE_MASTER
WHERE STORE_ID = 'STORE007'
ORDER BY SNAPSHOT_DATE;

-- Fixture-only assertion, expected PASS if exactly this 17-file sample was used.
SELECT IFF(
    (SELECT COUNT(*) FROM RETAIL_DWH.STG.ITEM_MASTER) = 150
    AND (SELECT COUNT(*) FROM RETAIL_DWH.STG.STORE_MASTER) = 60
    AND (SELECT COUNT(*) FROM RETAIL_DWH.STG.POS_SALES) = 150
    AND (SELECT COUNT(*) FROM RETAIL_DWH.STG.INVENTORY_SNAPSHOT) = 150
    AND (SELECT COUNT(*) FROM RETAIL_DWH.TMP.ITEM_MASTER) = 150
    AND (SELECT COUNT(*) FROM RETAIL_DWH.TMP.STORE_MASTER) = 60
    AND (SELECT COUNT(*) FROM RETAIL_DWH.TMP.POS_SALES) = 145
    AND (SELECT COUNT(*) FROM RETAIL_DWH.TMP.INVENTORY_SNAPSHOT) = 150
    AND (SELECT COUNT(*) FROM RETAIL_DWH.DQ.QUARANTINE_RECORDS) = 5
    AND (SELECT SUM(NET_SALES) FROM RETAIL_DWH.TMP.POS_SALES) = 1566.15,
    'PASS', 'FAIL'
) AS SAMPLE_STAGE5_RESULT;
