-- Production reconciliation. Expectations are derived from actual STG/TMP/DQ;
-- no reliance on tests/fixtures/expected_results.json.
-- Returns one result per observed business date. DAG fails if STATUS <> PASS.
WITH dates AS (
    SELECT SOURCE_FILE_DATE AS BUSINESS_DATE FROM RETAIL_DWH.STG.POS_SALES
    UNION
    SELECT SALE_DATE FROM RETAIL_DWH.TMP.POS_SALES
    UNION
    SELECT SOURCE_FILE_DATE FROM RETAIL_DWH.DQ.QUARANTINE_RECORDS
      WHERE SOURCE_TYPE = 'pos_sales'
    UNION
    SELECT SALE_DATE FROM RETAIL_DWH.TGT.FCT_SALES
), raw_sales AS (
    SELECT SOURCE_FILE_DATE AS BUSINESS_DATE,
           COUNT(*) AS RAW_ROWS,
           COALESCE(SUM(TRY_TO_DECIMAL(RAW_PAYLOAD:net_sales::VARCHAR, 18, 2)), 0) AS RAW_AMOUNT,
           COUNT_IF(TRY_TO_DECIMAL(RAW_PAYLOAD:net_sales::VARCHAR, 18, 2) IS NULL) AS UNPARSEABLE_RAW_AMOUNTS
    FROM RETAIL_DWH.STG.POS_SALES
    GROUP BY SOURCE_FILE_DATE
), clean_sales AS (
    SELECT SALE_DATE AS BUSINESS_DATE,
           COUNT(*) AS ACCEPTED_ROWS,
           COALESCE(SUM(NET_SALES), 0) AS ACCEPTED_AMOUNT
    FROM RETAIL_DWH.TMP.POS_SALES
    GROUP BY SALE_DATE
), rejected_sales AS (
    SELECT SOURCE_FILE_DATE AS BUSINESS_DATE,
           COUNT(*) AS REJECTED_ROWS,
           COALESCE(SUM(TRY_TO_DECIMAL(RAW_PAYLOAD:net_sales::VARCHAR, 18, 2)), 0) AS REJECTED_AMOUNT,
           COUNT_IF(TRY_TO_DECIMAL(RAW_PAYLOAD:net_sales::VARCHAR, 18, 2) IS NULL) AS UNPARSEABLE_REJECTED_AMOUNTS
    FROM RETAIL_DWH.DQ.QUARANTINE_RECORDS
    WHERE SOURCE_TYPE = 'pos_sales'
    GROUP BY SOURCE_FILE_DATE
), gold_sales AS (
    SELECT SALE_DATE AS BUSINESS_DATE,
           COUNT(*) AS GOLD_ROWS,
           COALESCE(SUM(NET_SALES), 0) AS GOLD_AMOUNT
    FROM RETAIL_DWH.TGT.FCT_SALES
    GROUP BY SALE_DATE
), compared AS (
    SELECT d.BUSINESS_DATE,
           COALESCE(r.RAW_ROWS,0) AS RAW_ROWS,
           COALESCE(c.ACCEPTED_ROWS,0) AS ACCEPTED_ROWS,
           COALESCE(q.REJECTED_ROWS,0) AS REJECTED_ROWS,
           COALESCE(g.GOLD_ROWS,0) AS GOLD_ROWS,
           COALESCE(r.RAW_AMOUNT,0) AS RAW_AMOUNT,
           COALESCE(c.ACCEPTED_AMOUNT,0) AS ACCEPTED_AMOUNT,
           COALESCE(q.REJECTED_AMOUNT,0) AS REJECTED_AMOUNT,
           COALESCE(g.GOLD_AMOUNT,0) AS GOLD_AMOUNT,
           COALESCE(r.UNPARSEABLE_RAW_AMOUNTS,0) AS UNPARSEABLE_RAW_AMOUNTS,
           COALESCE(q.UNPARSEABLE_REJECTED_AMOUNTS,0) AS UNPARSEABLE_REJECTED_AMOUNTS
    FROM dates d
    LEFT JOIN raw_sales r ON d.BUSINESS_DATE=r.BUSINESS_DATE
    LEFT JOIN clean_sales c ON d.BUSINESS_DATE=c.BUSINESS_DATE
    LEFT JOIN rejected_sales q ON d.BUSINESS_DATE=q.BUSINESS_DATE
    LEFT JOIN gold_sales g ON d.BUSINESS_DATE=g.BUSINESS_DATE
)
SELECT *,
       CASE
         WHEN RAW_ROWS > 0
          AND UNPARSEABLE_RAW_AMOUNTS = 0
          AND UNPARSEABLE_REJECTED_AMOUNTS = 0
          AND RAW_ROWS = ACCEPTED_ROWS + REJECTED_ROWS
          AND GOLD_ROWS = ACCEPTED_ROWS
          AND ABS(RAW_AMOUNT - ACCEPTED_AMOUNT - REJECTED_AMOUNT) <= 0.005
          AND ABS(GOLD_AMOUNT - ACCEPTED_AMOUNT) <= 0.005
         THEN 'PASS' ELSE 'FAIL' END AS STATUS
FROM compared
ORDER BY BUSINESS_DATE
