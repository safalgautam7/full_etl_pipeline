-- Inventory snapshots are positions, not transactions.
-- The historical effective-date behavior belongs in TGT.FCT_INVENTORY.
CREATE OR REPLACE TEMPORARY TABLE RETAIL_DWH.TMP.WORK_INVENTORY_SNAPSHOT AS
WITH parsed AS (
    SELECT
        s.SOURCE_ROW_ID, s.SOURCE_FILE_ID, s.SOURCE_FILE_NAME,
        s.SOURCE_FILE_DATE, s.SOURCE_ROW_NUMBER, s.BATCH_ID,
        s.RAW_PAYLOAD,
        TRY_TO_DATE(NULLIF(TRIM(s.RAW_PAYLOAD:snapshot_date::VARCHAR), ''), 'YYYY-MM-DD') AS SNAPSHOT_DATE,
        NULLIF(TRIM(s.RAW_PAYLOAD:store_id::VARCHAR), '') AS STORE_ID,
        NULLIF(TRIM(s.RAW_PAYLOAD:item_id::VARCHAR), '') AS ITEM_ID,
        TRY_TO_NUMBER(NULLIF(TRIM(s.RAW_PAYLOAD:quantity_on_hand::VARCHAR), ''), 38, 0) AS QUANTITY_ON_HAND,
        TRY_TO_DECIMAL(NULLIF(TRIM(s.RAW_PAYLOAD:unit_cost::VARCHAR), ''), 18, 2) AS UNIT_COST,
        TRY_TO_DECIMAL(NULLIF(TRIM(s.RAW_PAYLOAD:inventory_value::VARCHAR), ''), 18, 2) AS INVENTORY_VALUE
    FROM RETAIL_DWH.STG.INVENTORY_SNAPSHOT s
), item_snapshot_dates AS (
    SELECT d.SNAPSHOT_DATE, MAX(m.SNAPSHOT_DATE) AS EFFECTIVE_SNAPSHOT_DATE
    FROM (SELECT DISTINCT SNAPSHOT_DATE FROM parsed WHERE SNAPSHOT_DATE IS NOT NULL) d
    LEFT JOIN (SELECT DISTINCT SNAPSHOT_DATE FROM RETAIL_DWH.TMP.ITEM_MASTER) m
        ON m.SNAPSHOT_DATE <= d.SNAPSHOT_DATE
    GROUP BY d.SNAPSHOT_DATE
), store_snapshot_dates AS (
    SELECT d.SNAPSHOT_DATE, MAX(m.SNAPSHOT_DATE) AS EFFECTIVE_SNAPSHOT_DATE
    FROM (SELECT DISTINCT SNAPSHOT_DATE FROM parsed WHERE SNAPSHOT_DATE IS NOT NULL) d
    LEFT JOIN (SELECT DISTINCT SNAPSHOT_DATE FROM RETAIL_DWH.TMP.STORE_MASTER) m
        ON m.SNAPSHOT_DATE <= d.SNAPSHOT_DATE
    GROUP BY d.SNAPSHOT_DATE
), checked AS (
    SELECT p.*,
        CASE
            WHEN p.SNAPSHOT_DATE IS NULL OR p.SNAPSHOT_DATE <> p.SOURCE_FILE_DATE THEN 'INVALID_SNAPSHOT_DATE'
            WHEN p.STORE_ID IS NULL THEN 'NULL_STORE_ID'
            WHEN p.ITEM_ID IS NULL THEN 'NULL_ITEM_ID'
            WHEN p.QUANTITY_ON_HAND IS NULL
                OR NOT REGEXP_LIKE(TRIM(p.RAW_PAYLOAD:quantity_on_hand::VARCHAR), '^-?[0-9]+$')
                OR p.QUANTITY_ON_HAND < 0 THEN 'INVALID_QUANTITY_ON_HAND'
            WHEN p.UNIT_COST IS NULL OR p.UNIT_COST < 0 THEN 'INVALID_UNIT_COST'
            WHEN p.INVENTORY_VALUE IS NULL OR p.INVENTORY_VALUE < 0 THEN 'INVALID_INVENTORY_VALUE'
            WHEN ABS(p.INVENTORY_VALUE - p.QUANTITY_ON_HAND * p.UNIT_COST) > 0.01
                THEN 'INVENTORY_VALUE_MISMATCH'
            WHEN im.ITEM_ID IS NULL THEN 'UNKNOWN_ITEM_ID'
            WHEN sm.STORE_ID IS NULL THEN 'UNKNOWN_STORE_ID'
            ELSE NULL
        END AS BASE_REJECT_REASON
    FROM parsed p
    LEFT JOIN item_snapshot_dates idt ON idt.SNAPSHOT_DATE = p.SNAPSHOT_DATE
    LEFT JOIN store_snapshot_dates sdt ON sdt.SNAPSHOT_DATE = p.SNAPSHOT_DATE
    LEFT JOIN RETAIL_DWH.TMP.ITEM_MASTER im
      ON im.SNAPSHOT_DATE = idt.EFFECTIVE_SNAPSHOT_DATE AND im.ITEM_ID = p.ITEM_ID
    LEFT JOIN RETAIL_DWH.TMP.STORE_MASTER sm
      ON sm.SNAPSHOT_DATE = sdt.EFFECTIVE_SNAPSHOT_DATE AND sm.STORE_ID = p.STORE_ID
), ranked AS (
    SELECT c.*,
        ROW_NUMBER() OVER (
            PARTITION BY SNAPSHOT_DATE, STORE_ID, ITEM_ID
            ORDER BY IFF(BASE_REJECT_REASON IS NULL, 0, 1),
                     SOURCE_FILE_DATE, SOURCE_ROW_NUMBER, SOURCE_ROW_ID
        ) AS BUSINESS_KEY_RN
    FROM checked c
)
SELECT r.*,
       CASE
           WHEN BASE_REJECT_REASON IS NOT NULL THEN BASE_REJECT_REASON
           WHEN BUSINESS_KEY_RN > 1 THEN 'DUPLICATE_INVENTORY_POSITION'
           ELSE NULL
       END AS REJECT_REASON
FROM ranked r
