-- Weekly master input: 2026-11-09 and the exceptional 2026-11-11 snapshot.
-- Do not fabricate store snapshots for dates where no file arrived.
CREATE OR REPLACE TEMPORARY TABLE RETAIL_DWH.TMP.WORK_STORE_MASTER AS
WITH parsed AS (
    SELECT
        s.SOURCE_ROW_ID, s.SOURCE_FILE_ID, s.SOURCE_FILE_NAME,
        s.SOURCE_FILE_DATE, s.SOURCE_ROW_NUMBER, s.BATCH_ID,
        s.RAW_PAYLOAD,
        TRY_TO_DATE(NULLIF(TRIM(s.RAW_PAYLOAD:snapshot_date::VARCHAR), ''), 'YYYY-MM-DD') AS SNAPSHOT_DATE,
        NULLIF(TRIM(s.RAW_PAYLOAD:store_id::VARCHAR), '') AS STORE_ID,
        NULLIF(TRIM(s.RAW_PAYLOAD:store_name::VARCHAR), '') AS STORE_NAME,
        NULLIF(TRIM(s.RAW_PAYLOAD:district_id::VARCHAR), '') AS DISTRICT_ID,
        NULLIF(TRIM(s.RAW_PAYLOAD:district_name::VARCHAR), '') AS DISTRICT_NAME,
        NULLIF(TRIM(s.RAW_PAYLOAD:city::VARCHAR), '') AS CITY,
        NULLIF(TRIM(s.RAW_PAYLOAD:region::VARCHAR), '') AS REGION,
        CASE UPPER(TRIM(s.RAW_PAYLOAD:is_active::VARCHAR))
            WHEN 'Y' THEN TRUE WHEN 'N' THEN FALSE ELSE NULL
        END AS IS_ACTIVE
    FROM RETAIL_DWH.STG.STORE_MASTER s
), checked AS (
    SELECT p.*,
        CASE
            WHEN SNAPSHOT_DATE IS NULL OR SNAPSHOT_DATE <> SOURCE_FILE_DATE THEN 'INVALID_SNAPSHOT_DATE'
            WHEN STORE_ID IS NULL THEN 'NULL_STORE_ID'
            WHEN STORE_NAME IS NULL THEN 'NULL_STORE_NAME'
            WHEN DISTRICT_ID IS NULL THEN 'NULL_DISTRICT_ID'
            WHEN DISTRICT_NAME IS NULL THEN 'NULL_DISTRICT_NAME'
            WHEN IS_ACTIVE IS NULL THEN 'INVALID_IS_ACTIVE'
            ELSE NULL
        END AS BASE_REJECT_REASON
    FROM parsed p
), ranked AS (
    SELECT c.*,
        ROW_NUMBER() OVER (
            PARTITION BY SNAPSHOT_DATE, STORE_ID
            ORDER BY IFF(BASE_REJECT_REASON IS NULL, 0, 1),
                     SOURCE_FILE_DATE, SOURCE_ROW_NUMBER, SOURCE_ROW_ID
        ) AS BUSINESS_KEY_RN
    FROM checked c
)
SELECT r.*,
       CASE
           WHEN BASE_REJECT_REASON IS NOT NULL THEN BASE_REJECT_REASON
           WHEN BUSINESS_KEY_RN > 1 THEN 'DUPLICATE_STORE_SNAPSHOT'
           ELSE NULL
       END AS REJECT_REASON
FROM ranked r
