-- Sales must reference an item and a store effective on the sale date.
-- Prioritize business-quality errors before duplicate detection.
-- Canonical duplicate line = earliest eligible source physical row.
CREATE OR REPLACE TEMPORARY TABLE RETAIL_DWH.TMP.WORK_POS_SALES AS
WITH parsed AS (
    SELECT
        s.SOURCE_ROW_ID, s.SOURCE_FILE_ID, s.SOURCE_FILE_NAME,
        s.SOURCE_FILE_DATE, s.SOURCE_ROW_NUMBER, s.BATCH_ID,
        s.RAW_PAYLOAD,
        TRY_TO_DATE(NULLIF(TRIM(s.RAW_PAYLOAD:sale_date::VARCHAR), ''), 'YYYY-MM-DD') AS SALE_DATE,
        NULLIF(TRIM(s.RAW_PAYLOAD:transaction_id::VARCHAR), '') AS TRANSACTION_ID,
        TRY_TO_NUMBER(NULLIF(TRIM(s.RAW_PAYLOAD:line_number::VARCHAR), ''), 38, 0) AS LINE_NUMBER,
        NULLIF(TRIM(s.RAW_PAYLOAD:store_id::VARCHAR), '') AS STORE_ID,
        NULLIF(TRIM(s.RAW_PAYLOAD:item_id::VARCHAR), '') AS ITEM_ID,
        TRY_TO_NUMBER(NULLIF(TRIM(s.RAW_PAYLOAD:quantity::VARCHAR), ''), 38, 0) AS QUANTITY,
        TRY_TO_DECIMAL(NULLIF(TRIM(s.RAW_PAYLOAD:unit_price::VARCHAR), ''), 18, 2) AS UNIT_PRICE,
        TRY_TO_DECIMAL(NULLIF(TRIM(s.RAW_PAYLOAD:discount_amount::VARCHAR), ''), 18, 2) AS DISCOUNT_AMOUNT,
        TRY_TO_DECIMAL(NULLIF(TRIM(s.RAW_PAYLOAD:net_sales::VARCHAR), ''), 18, 2) AS NET_SALES,
        NULLIF(UPPER(TRIM(s.RAW_PAYLOAD:payment_method::VARCHAR)), '') AS PAYMENT_METHOD
    FROM RETAIL_DWH.STG.POS_SALES s
), item_snapshot_dates AS (
    SELECT d.SALE_DATE, MAX(m.SNAPSHOT_DATE) AS EFFECTIVE_SNAPSHOT_DATE
    FROM (SELECT DISTINCT SALE_DATE FROM parsed WHERE SALE_DATE IS NOT NULL) d
    LEFT JOIN (SELECT DISTINCT SNAPSHOT_DATE FROM RETAIL_DWH.TMP.ITEM_MASTER) m
        ON m.SNAPSHOT_DATE <= d.SALE_DATE
    GROUP BY d.SALE_DATE
), store_snapshot_dates AS (
    SELECT d.SALE_DATE, MAX(m.SNAPSHOT_DATE) AS EFFECTIVE_SNAPSHOT_DATE
    FROM (SELECT DISTINCT SALE_DATE FROM parsed WHERE SALE_DATE IS NOT NULL) d
    LEFT JOIN (SELECT DISTINCT SNAPSHOT_DATE FROM RETAIL_DWH.TMP.STORE_MASTER) m
        ON m.SNAPSHOT_DATE <= d.SALE_DATE
    GROUP BY d.SALE_DATE
), checked AS (
    SELECT p.*,
        CASE
            WHEN p.SALE_DATE IS NULL OR p.SALE_DATE <> p.SOURCE_FILE_DATE THEN 'INVALID_SALE_DATE'
            WHEN p.TRANSACTION_ID IS NULL THEN 'NULL_TRANSACTION_ID'
            WHEN p.LINE_NUMBER IS NULL OR p.LINE_NUMBER <= 0
                 OR NOT REGEXP_LIKE(TRIM(p.RAW_PAYLOAD:line_number::VARCHAR), '^[0-9]+$')
                THEN 'INVALID_LINE_NUMBER'
            WHEN p.STORE_ID IS NULL THEN 'NULL_STORE_ID'
            WHEN p.ITEM_ID IS NULL THEN 'NULL_ITEM_ID'
            WHEN p.QUANTITY IS NULL
                 OR NOT REGEXP_LIKE(TRIM(p.RAW_PAYLOAD:quantity::VARCHAR), '^-?[0-9]+$')
                THEN 'INVALID_QUANTITY'
            WHEN p.QUANTITY < 0 THEN 'NEGATIVE_QUANTITY'
            WHEN p.QUANTITY = 0 THEN 'ZERO_QUANTITY'
            WHEN p.UNIT_PRICE IS NULL OR p.UNIT_PRICE < 0 THEN 'INVALID_UNIT_PRICE'
            WHEN p.DISCOUNT_AMOUNT IS NULL OR p.DISCOUNT_AMOUNT < 0 THEN 'INVALID_DISCOUNT'
            WHEN p.NET_SALES IS NULL THEN 'INVALID_NET_SALES'
            WHEN ABS(p.NET_SALES - (p.QUANTITY * p.UNIT_PRICE - p.DISCOUNT_AMOUNT)) > 0.01
                THEN 'AMOUNT_MISMATCH'
            WHEN im.ITEM_ID IS NULL THEN 'UNKNOWN_ITEM_ID'
            WHEN sm.STORE_ID IS NULL THEN 'UNKNOWN_STORE_ID'
            ELSE NULL
        END AS BASE_REJECT_REASON
    FROM parsed p
    LEFT JOIN item_snapshot_dates idt ON idt.SALE_DATE = p.SALE_DATE
    LEFT JOIN store_snapshot_dates sdt ON sdt.SALE_DATE = p.SALE_DATE
    LEFT JOIN RETAIL_DWH.TMP.ITEM_MASTER im
      ON im.SNAPSHOT_DATE = idt.EFFECTIVE_SNAPSHOT_DATE AND im.ITEM_ID = p.ITEM_ID
    LEFT JOIN RETAIL_DWH.TMP.STORE_MASTER sm
      ON sm.SNAPSHOT_DATE = sdt.EFFECTIVE_SNAPSHOT_DATE AND sm.STORE_ID = p.STORE_ID
), ranked AS (
    SELECT c.*,
        ROW_NUMBER() OVER (
            PARTITION BY TRANSACTION_ID, LINE_NUMBER
            ORDER BY IFF(BASE_REJECT_REASON IS NULL, 0, 1),
                     SOURCE_FILE_DATE, SOURCE_ROW_NUMBER, SOURCE_ROW_ID
        ) AS BUSINESS_KEY_RN
    FROM checked c
)
SELECT r.*,
       CASE
           WHEN BASE_REJECT_REASON IS NOT NULL THEN BASE_REJECT_REASON
           WHEN BUSINESS_KEY_RN > 1 THEN 'DUPLICATE_SALES_LINE'
           ELSE NULL
       END AS REJECT_REASON
FROM ranked r
