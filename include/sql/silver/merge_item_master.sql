-- Exact null-safe comparison; unchanged rows retain PROCESSED_AT.
MERGE INTO {tmp} t
USING (SELECT * FROM {work} WHERE REJECT_REASON IS NULL) s
ON t.SOURCE_ROW_ID = s.SOURCE_ROW_ID
WHEN MATCHED AND (
    t.SOURCE_FILE_ID IS DISTINCT FROM s.SOURCE_FILE_ID OR
    t.SOURCE_FILE_NAME IS DISTINCT FROM s.SOURCE_FILE_NAME OR
    t.SOURCE_FILE_DATE IS DISTINCT FROM s.SOURCE_FILE_DATE OR
    t.SOURCE_ROW_NUMBER IS DISTINCT FROM s.SOURCE_ROW_NUMBER OR
    t.BATCH_ID IS DISTINCT FROM s.BATCH_ID OR
    t.SNAPSHOT_DATE IS DISTINCT FROM s.SNAPSHOT_DATE OR
    t.ITEM_ID IS DISTINCT FROM s.ITEM_ID OR
    t.ITEM_NAME IS DISTINCT FROM s.ITEM_NAME OR
    t.SUBCLASS_ID IS DISTINCT FROM s.SUBCLASS_ID OR
    t.SUBCLASS_NAME IS DISTINCT FROM s.SUBCLASS_NAME OR
    t.DEPARTMENT_ID IS DISTINCT FROM s.DEPARTMENT_ID OR
    t.DEPARTMENT_NAME IS DISTINCT FROM s.DEPARTMENT_NAME OR
    t.CLASS_ID IS DISTINCT FROM s.CLASS_ID OR
    t.CLASS_NAME IS DISTINCT FROM s.CLASS_NAME OR
    t.BRAND IS DISTINCT FROM s.BRAND OR
    t.UNIT_OF_MEASURE IS DISTINCT FROM s.UNIT_OF_MEASURE OR
    t.LIST_PRICE IS DISTINCT FROM s.LIST_PRICE OR
    t.IS_ACTIVE IS DISTINCT FROM s.IS_ACTIVE
) THEN UPDATE SET
    SOURCE_FILE_ID = s.SOURCE_FILE_ID, SOURCE_FILE_NAME = s.SOURCE_FILE_NAME,
    SOURCE_FILE_DATE = s.SOURCE_FILE_DATE, SOURCE_ROW_NUMBER = s.SOURCE_ROW_NUMBER,
    BATCH_ID = s.BATCH_ID, SNAPSHOT_DATE = s.SNAPSHOT_DATE,
    ITEM_ID = s.ITEM_ID, ITEM_NAME = s.ITEM_NAME,
    SUBCLASS_ID = s.SUBCLASS_ID, SUBCLASS_NAME = s.SUBCLASS_NAME,
    DEPARTMENT_ID = s.DEPARTMENT_ID, DEPARTMENT_NAME = s.DEPARTMENT_NAME,
    CLASS_ID = s.CLASS_ID, CLASS_NAME = s.CLASS_NAME,
    BRAND = s.BRAND, UNIT_OF_MEASURE = s.UNIT_OF_MEASURE,
    LIST_PRICE = s.LIST_PRICE, IS_ACTIVE = s.IS_ACTIVE,
    PROCESSED_AT = CURRENT_TIMESTAMP
WHEN NOT MATCHED THEN INSERT (
    SOURCE_ROW_ID, SOURCE_FILE_ID, SOURCE_FILE_NAME, SOURCE_FILE_DATE, SOURCE_ROW_NUMBER,
    BATCH_ID, SNAPSHOT_DATE, ITEM_ID, ITEM_NAME, SUBCLASS_ID, SUBCLASS_NAME,
    DEPARTMENT_ID, DEPARTMENT_NAME, CLASS_ID, CLASS_NAME,
    BRAND, UNIT_OF_MEASURE, LIST_PRICE, IS_ACTIVE
) VALUES (
    s.SOURCE_ROW_ID, s.SOURCE_FILE_ID, s.SOURCE_FILE_NAME, s.SOURCE_FILE_DATE, s.SOURCE_ROW_NUMBER,
    s.BATCH_ID, s.SNAPSHOT_DATE, s.ITEM_ID, s.ITEM_NAME, s.SUBCLASS_ID, s.SUBCLASS_NAME,
    s.DEPARTMENT_ID, s.DEPARTMENT_NAME, s.CLASS_ID, s.CLASS_NAME,
    s.BRAND, s.UNIT_OF_MEASURE, s.LIST_PRICE, s.IS_ACTIVE
)
