-- One statement. Builds a session-local decision table from immutable STG rows.
-- RAW_PAYLOAD keys match item_master_YYYYMMDD.csv exactly.
CREATE OR REPLACE TEMPORARY TABLE RETAIL_DWH.TMP.WORK_ITEM_MASTER AS
WITH parsed AS (
    SELECT
        s.SOURCE_ROW_ID, s.SOURCE_FILE_ID, s.SOURCE_FILE_NAME,
        s.SOURCE_FILE_DATE, s.SOURCE_ROW_NUMBER, s.BATCH_ID,
        s.RAW_PAYLOAD,
        TRY_TO_DATE(NULLIF(TRIM(s.RAW_PAYLOAD:snapshot_date::VARCHAR), ''), 'YYYY-MM-DD') AS SNAPSHOT_DATE,
        NULLIF(TRIM(s.RAW_PAYLOAD:item_id::VARCHAR), '') AS ITEM_ID,
        NULLIF(TRIM(s.RAW_PAYLOAD:item_name::VARCHAR), '') AS ITEM_NAME,
        NULLIF(TRIM(s.RAW_PAYLOAD:subclass_id::VARCHAR), '') AS SUBCLASS_ID,
        NULLIF(TRIM(s.RAW_PAYLOAD:subclass_name::VARCHAR), '') AS SUBCLASS_NAME,
        NULLIF(TRIM(s.RAW_PAYLOAD:department_id::VARCHAR), '') AS DEPARTMENT_ID,
        NULLIF(TRIM(s.RAW_PAYLOAD:department_name::VARCHAR), '') AS DEPARTMENT_NAME,
        NULLIF(TRIM(s.RAW_PAYLOAD:class_id::VARCHAR), '') AS CLASS_ID,
        NULLIF(TRIM(s.RAW_PAYLOAD:class_name::VARCHAR), '') AS CLASS_NAME,
        NULLIF(TRIM(s.RAW_PAYLOAD:brand::VARCHAR), '') AS BRAND,
        NULLIF(UPPER(TRIM(s.RAW_PAYLOAD:unit_of_measure::VARCHAR)), '') AS UNIT_OF_MEASURE,
        TRY_TO_DECIMAL(NULLIF(TRIM(s.RAW_PAYLOAD:list_price::VARCHAR), ''), 18, 2) AS LIST_PRICE,
        CASE UPPER(TRIM(s.RAW_PAYLOAD:is_active::VARCHAR))
            WHEN 'Y' THEN TRUE WHEN 'N' THEN FALSE ELSE NULL
        END AS IS_ACTIVE
    FROM RETAIL_DWH.STG.ITEM_MASTER s
), checked AS (
    SELECT p.*,
        CASE
            WHEN SNAPSHOT_DATE IS NULL OR SNAPSHOT_DATE <> SOURCE_FILE_DATE THEN 'INVALID_SNAPSHOT_DATE'
            WHEN ITEM_ID IS NULL THEN 'NULL_ITEM_ID'
            WHEN ITEM_NAME IS NULL THEN 'NULL_ITEM_NAME'
            WHEN SUBCLASS_ID IS NULL THEN 'NULL_SUBCLASS_ID'
            WHEN SUBCLASS_NAME IS NULL THEN 'NULL_SUBCLASS_NAME'
            WHEN LIST_PRICE IS NULL OR LIST_PRICE < 0 THEN 'INVALID_LIST_PRICE'
            WHEN IS_ACTIVE IS NULL THEN 'INVALID_IS_ACTIVE'
            WHEN DEPARTMENT_ID IS NULL OR DEPARTMENT_NAME IS NULL
              OR CLASS_ID IS NULL OR CLASS_NAME IS NULL THEN 'INCOMPLETE_ITEM_HIERARCHY'
            ELSE NULL
        END AS BASE_REJECT_REASON
    FROM parsed p
), ranked AS (
    SELECT c.*,
        ROW_NUMBER() OVER (
            PARTITION BY SNAPSHOT_DATE, ITEM_ID
            ORDER BY IFF(BASE_REJECT_REASON IS NULL, 0, 1),
                     SOURCE_FILE_DATE, SOURCE_ROW_NUMBER, SOURCE_ROW_ID
        ) AS BUSINESS_KEY_RN
    FROM checked c
)
SELECT r.*,
       CASE
           WHEN BASE_REJECT_REASON IS NOT NULL THEN BASE_REJECT_REASON
           WHEN BUSINESS_KEY_RN > 1 THEN 'DUPLICATE_ITEM_SNAPSHOT'
           ELSE NULL
       END AS REJECT_REASON
FROM ranked r
