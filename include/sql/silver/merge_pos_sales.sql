MERGE INTO {tmp} t
USING (SELECT * FROM {work} WHERE REJECT_REASON IS NULL) s
ON t.SOURCE_ROW_ID = s.SOURCE_ROW_ID
WHEN MATCHED AND (
    t.SOURCE_FILE_ID IS DISTINCT FROM s.SOURCE_FILE_ID OR
    t.SOURCE_FILE_NAME IS DISTINCT FROM s.SOURCE_FILE_NAME OR
    t.SOURCE_FILE_DATE IS DISTINCT FROM s.SOURCE_FILE_DATE OR
    t.SOURCE_ROW_NUMBER IS DISTINCT FROM s.SOURCE_ROW_NUMBER OR
    t.BATCH_ID IS DISTINCT FROM s.BATCH_ID OR
    t.SALE_DATE IS DISTINCT FROM s.SALE_DATE OR
    t.TRANSACTION_ID IS DISTINCT FROM s.TRANSACTION_ID OR
    t.LINE_NUMBER IS DISTINCT FROM s.LINE_NUMBER OR
    t.STORE_ID IS DISTINCT FROM s.STORE_ID OR
    t.ITEM_ID IS DISTINCT FROM s.ITEM_ID OR
    t.QUANTITY IS DISTINCT FROM s.QUANTITY OR
    t.UNIT_PRICE IS DISTINCT FROM s.UNIT_PRICE OR
    t.DISCOUNT_AMOUNT IS DISTINCT FROM s.DISCOUNT_AMOUNT OR
    t.NET_SALES IS DISTINCT FROM s.NET_SALES OR
    t.PAYMENT_METHOD IS DISTINCT FROM s.PAYMENT_METHOD
) THEN UPDATE SET
    SOURCE_FILE_ID = s.SOURCE_FILE_ID, SOURCE_FILE_NAME = s.SOURCE_FILE_NAME,
    SOURCE_FILE_DATE = s.SOURCE_FILE_DATE, SOURCE_ROW_NUMBER = s.SOURCE_ROW_NUMBER,
    BATCH_ID = s.BATCH_ID, SALE_DATE = s.SALE_DATE,
    TRANSACTION_ID = s.TRANSACTION_ID, LINE_NUMBER = s.LINE_NUMBER,
    STORE_ID = s.STORE_ID, ITEM_ID = s.ITEM_ID, QUANTITY = s.QUANTITY,
    UNIT_PRICE = s.UNIT_PRICE, DISCOUNT_AMOUNT = s.DISCOUNT_AMOUNT,
    NET_SALES = s.NET_SALES, PAYMENT_METHOD = s.PAYMENT_METHOD,
    PROCESSED_AT = CURRENT_TIMESTAMP
WHEN NOT MATCHED THEN INSERT (
    SOURCE_ROW_ID, SOURCE_FILE_ID, SOURCE_FILE_NAME, SOURCE_FILE_DATE, SOURCE_ROW_NUMBER,
    BATCH_ID, SALE_DATE, TRANSACTION_ID, LINE_NUMBER, STORE_ID, ITEM_ID,
    QUANTITY, UNIT_PRICE, DISCOUNT_AMOUNT, NET_SALES, PAYMENT_METHOD
) VALUES (
    s.SOURCE_ROW_ID, s.SOURCE_FILE_ID, s.SOURCE_FILE_NAME, s.SOURCE_FILE_DATE, s.SOURCE_ROW_NUMBER,
    s.BATCH_ID, s.SALE_DATE, s.TRANSACTION_ID, s.LINE_NUMBER, s.STORE_ID, s.ITEM_ID,
    s.QUANTITY, s.UNIT_PRICE, s.DISCOUNT_AMOUNT, s.NET_SALES, s.PAYMENT_METHOD
)
