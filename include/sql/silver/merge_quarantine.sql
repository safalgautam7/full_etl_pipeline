-- Current disposition keyed by source + immutable physical row identity.
-- Do not compare attempt IDs or processing time. Raw lineage comes from STG.
MERGE INTO {quarantine} t
USING (
    SELECT SOURCE_ROW_ID, SOURCE_FILE_ID, SOURCE_FILE_NAME, SOURCE_FILE_DATE,
           SOURCE_ROW_NUMBER, BATCH_ID, RAW_PAYLOAD,
           %s AS SOURCE_TYPE, REJECT_REASON AS REASON_CODE,
           'Validation failed: ' || REJECT_REASON AS REASON_DETAIL
    FROM {work} WHERE REJECT_REASON IS NOT NULL
) s
ON t.SOURCE_TYPE = s.SOURCE_TYPE AND t.SOURCE_ROW_ID = s.SOURCE_ROW_ID
WHEN MATCHED AND (
    t.SOURCE_FILE_ID IS DISTINCT FROM s.SOURCE_FILE_ID OR
    t.SOURCE_FILE_NAME IS DISTINCT FROM s.SOURCE_FILE_NAME OR
    t.SOURCE_FILE_DATE IS DISTINCT FROM s.SOURCE_FILE_DATE OR
    t.SOURCE_ROW_NUMBER IS DISTINCT FROM s.SOURCE_ROW_NUMBER OR
    t.BATCH_ID IS DISTINCT FROM s.BATCH_ID OR
    t.REASON_CODE IS DISTINCT FROM s.REASON_CODE OR
    t.REASON_DETAIL IS DISTINCT FROM s.REASON_DETAIL OR
    t.RAW_PAYLOAD IS DISTINCT FROM s.RAW_PAYLOAD
) THEN UPDATE SET
    SOURCE_FILE_ID = s.SOURCE_FILE_ID, SOURCE_FILE_NAME = s.SOURCE_FILE_NAME,
    SOURCE_FILE_DATE = s.SOURCE_FILE_DATE, SOURCE_ROW_NUMBER = s.SOURCE_ROW_NUMBER,
    BATCH_ID = s.BATCH_ID, REASON_CODE = s.REASON_CODE,
    REASON_DETAIL = s.REASON_DETAIL, RAW_PAYLOAD = s.RAW_PAYLOAD,
    REJECTED_AT = CURRENT_TIMESTAMP
WHEN NOT MATCHED THEN INSERT (
    SOURCE_ROW_ID, SOURCE_FILE_ID, SOURCE_FILE_NAME, SOURCE_FILE_DATE,
    SOURCE_ROW_NUMBER, SOURCE_TYPE, BATCH_ID, REASON_CODE, REASON_DETAIL, RAW_PAYLOAD
) VALUES (
    s.SOURCE_ROW_ID, s.SOURCE_FILE_ID, s.SOURCE_FILE_NAME, s.SOURCE_FILE_DATE,
    s.SOURCE_ROW_NUMBER, s.SOURCE_TYPE, s.BATCH_ID, s.REASON_CODE, s.REASON_DETAIL, s.RAW_PAYLOAD
)
