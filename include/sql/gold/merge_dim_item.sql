-- SCD Type 2: each unique (ITEM_ID, EFFECTIVE_FROM) is one version.
-- The entire close-and-insert history is applied atomically by one MERGE.
-- Do not overwrite existing ITEM_SK: omit it from the insert/update columns.
MERGE INTO RETAIL_DWH.TGT.DIM_ITEM t
USING RETAIL_DWH.TMP.WORK_DIM_ITEM s
ON t.ITEM_ID = s.ITEM_ID AND t.EFFECTIVE_FROM = s.EFFECTIVE_FROM
WHEN MATCHED AND (
    t.RECORD_HASH IS DISTINCT FROM s.RECORD_HASH OR
    t.SOURCE_ROW_ID IS DISTINCT FROM s.SOURCE_ROW_ID OR
    t.EFFECTIVE_TO IS DISTINCT FROM s.EFFECTIVE_TO OR
    t.IS_CURRENT IS DISTINCT FROM s.IS_CURRENT OR
    t.SUBCLASS_SK IS DISTINCT FROM s.SUBCLASS_SK
) THEN UPDATE SET
    t.ITEM_NAME = s.ITEM_NAME,
    t.BRAND = s.BRAND,
    t.UNIT_OF_MEASURE = s.UNIT_OF_MEASURE,
    t.LIST_PRICE = s.LIST_PRICE,
    t.SUBCLASS_ID = s.SUBCLASS_ID,
    t.SUBCLASS_SK = s.SUBCLASS_SK,
    t.DEPARTMENT_ID = s.DEPARTMENT_ID,
    t.DEPARTMENT_NAME = s.DEPARTMENT_NAME,
    t.CLASS_ID = s.CLASS_ID,
    t.CLASS_NAME = s.CLASS_NAME,
    t.IS_ACTIVE = s.IS_ACTIVE,
    t.EFFECTIVE_TO = s.EFFECTIVE_TO,
    t.IS_CURRENT = s.IS_CURRENT,
    t.RECORD_HASH = s.RECORD_HASH,
    t.SOURCE_ROW_ID = s.SOURCE_ROW_ID,
    t.REC_UPDT_TS = CURRENT_TIMESTAMP()
WHEN NOT MATCHED THEN INSERT (
    ITEM_ID, ITEM_NAME, BRAND, UNIT_OF_MEASURE, LIST_PRICE,
    SUBCLASS_ID, SUBCLASS_SK, IS_ACTIVE,
    DEPARTMENT_ID, DEPARTMENT_NAME, CLASS_ID, CLASS_NAME,
    EFFECTIVE_FROM, EFFECTIVE_TO, IS_CURRENT, RECORD_HASH, SOURCE_ROW_ID
) VALUES (
    s.ITEM_ID, s.ITEM_NAME, s.BRAND, s.UNIT_OF_MEASURE, s.LIST_PRICE,
    s.SUBCLASS_ID, s.SUBCLASS_SK, s.IS_ACTIVE,
    s.DEPARTMENT_ID, s.DEPARTMENT_NAME, s.CLASS_ID, s.CLASS_NAME,
    s.EFFECTIVE_FROM, s.EFFECTIVE_TO, s.IS_CURRENT, s.RECORD_HASH, s.SOURCE_ROW_ID
)
