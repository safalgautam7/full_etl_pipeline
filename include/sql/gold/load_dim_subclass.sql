-- SCD Type 1: keep latest subclass description, update only if changed.
-- Order by snapshot date; deterministic tie-breaker by source metadata.
MERGE INTO RETAIL_DWH.TGT.DIM_SUBCLASS t
USING (
    SELECT SUBCLASS_ID, SUBCLASS_NAME
    FROM RETAIL_DWH.TMP.ITEM_MASTER
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY SUBCLASS_ID
        ORDER BY SNAPSHOT_DATE DESC, SOURCE_FILE_NAME DESC,
                 SOURCE_ROW_NUMBER DESC, SOURCE_ROW_ID DESC
    ) = 1
) s
ON t.SUBCLASS_ID = s.SUBCLASS_ID
WHEN MATCHED AND t.SUBCLASS_NAME IS DISTINCT FROM s.SUBCLASS_NAME THEN
    UPDATE SET
        t.SUBCLASS_NAME = s.SUBCLASS_NAME,
        t.UPDATED_AT = CURRENT_TIMESTAMP()
WHEN NOT MATCHED THEN
    INSERT (SUBCLASS_ID, SUBCLASS_NAME)
    VALUES (s.SUBCLASS_ID, s.SUBCLASS_NAME)
