-- Bound dates are supplied by the Python calendar loader, not wall-clock time.
MERGE INTO RETAIL_DWH.TGT.DIM_DATE t
USING (
    SELECT TO_NUMBER(TO_CHAR(d, 'YYYYMMDD')) AS DATE_KEY,
           d AS CALENDAR_DATE, YEAR(d) AS CALENDAR_YEAR,
           QUARTER(d) AS QUARTER_NUMBER, MONTH(d) AS MONTH_NUMBER,
           TO_CHAR(d, 'MMMM') AS MONTH_NAME,
           YEAR(d) * 100 + MONTH(d) AS YEAR_MONTH_KEY,
           DAY(d) AS DAY_OF_MONTH, DAYOFWEEKISO(d) AS ISO_DAY_OF_WEEK,
           DECODE(DAYOFWEEKISO(d), 1, 'Monday', 2, 'Tuesday', 3, 'Wednesday',
                  4, 'Thursday', 5, 'Friday', 6, 'Saturday', 7, 'Sunday') AS DAY_NAME,
           WEEKISO(d) AS ISO_WEEK_NUMBER, YEAROFWEEKISO(d) AS ISO_WEEK_YEAR,
           DATE_TRUNC('MONTH', d)::DATE AS MONTH_START_DATE,
           LAST_DAY(d) AS MONTH_END_DATE
    FROM (
        SELECT DATEADD('DAY', ROW_NUMBER() OVER (ORDER BY SEQ4()) - 1,
                       TO_DATE(%s))::DATE AS d
        FROM TABLE(GENERATOR(ROWCOUNT => 73049))
    ) WHERE d <= TO_DATE(%s)
) s ON t.CALENDAR_DATE = s.CALENDAR_DATE
WHEN NOT MATCHED THEN INSERT (
    DATE_KEY, CALENDAR_DATE, CALENDAR_YEAR, QUARTER_NUMBER, MONTH_NUMBER,
    MONTH_NAME, YEAR_MONTH_KEY, DAY_OF_MONTH, ISO_DAY_OF_WEEK, DAY_NAME,
    ISO_WEEK_NUMBER, ISO_WEEK_YEAR, MONTH_START_DATE, MONTH_END_DATE
) VALUES (
    s.DATE_KEY, s.CALENDAR_DATE, s.CALENDAR_YEAR, s.QUARTER_NUMBER, s.MONTH_NUMBER,
    s.MONTH_NAME, s.YEAR_MONTH_KEY, s.DAY_OF_MONTH, s.ISO_DAY_OF_WEEK, s.DAY_NAME,
    s.ISO_WEEK_NUMBER, s.ISO_WEEK_YEAR, s.MONTH_START_DATE, s.MONTH_END_DATE
)
