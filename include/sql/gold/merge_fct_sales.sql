-- One source row per (TRANSACTION_ID, LINE_NUMBER) must already be guaranteed.
-- The existing source fixture uses this globally unique sales-line key.
-- If production transaction IDs are store-scoped, include STORE_ID in ON and
-- in the TMP duplicate-detection business key (contract change).
-- Updating only changed values preserves existing SK and REC_UPDT_TS on rerun.
MERGE INTO RETAIL_DWH.TGT.FCT_SALES t
USING RETAIL_DWH.TMP.WORK_FCT_SALES s
  ON t.TRANSACTION_ID = s.TRANSACTION_ID
 AND t.LINE_NUMBER = s.LINE_NUMBER
WHEN MATCHED AND (
    t.STORE_ID IS DISTINCT FROM s.STORE_ID OR
    t.ITEM_ID IS DISTINCT FROM s.ITEM_ID OR
    t.SALE_DATE IS DISTINCT FROM s.SALE_DATE OR
    t.ITEM_SK IS DISTINCT FROM s.ITEM_SK OR
    t.LOCN_SK IS DISTINCT FROM s.LOCN_SK OR
    t.QUANTITY IS DISTINCT FROM s.QUANTITY OR
    t.UNIT_PRICE IS DISTINCT FROM s.UNIT_PRICE OR
    t.DISCOUNT_AMOUNT IS DISTINCT FROM s.DISCOUNT_AMOUNT OR
    t.NET_SALES IS DISTINCT FROM s.NET_SALES OR
    t.SOURCE_ROW_ID IS DISTINCT FROM s.SOURCE_ROW_ID
) THEN UPDATE SET
    t.STORE_ID = s.STORE_ID,
    t.ITEM_ID = s.ITEM_ID,
    t.SALE_DATE = s.SALE_DATE,
    t.ITEM_SK = s.ITEM_SK,
    t.LOCN_SK = s.LOCN_SK,
    t.QUANTITY = s.QUANTITY,
    t.UNIT_PRICE = s.UNIT_PRICE,
    t.DISCOUNT_AMOUNT = s.DISCOUNT_AMOUNT,
    t.NET_SALES = s.NET_SALES,
    t.SOURCE_ROW_ID = s.SOURCE_ROW_ID,
    t.REC_UPDT_TS = CURRENT_TIMESTAMP()
WHEN NOT MATCHED THEN INSERT (
    TRANSACTION_ID, LINE_NUMBER, STORE_ID, ITEM_ID, SALE_DATE,
    ITEM_SK, LOCN_SK, QUANTITY, UNIT_PRICE, DISCOUNT_AMOUNT,
    NET_SALES, SOURCE_ROW_ID
) VALUES (
    s.TRANSACTION_ID, s.LINE_NUMBER, s.STORE_ID, s.ITEM_ID, s.SALE_DATE,
    s.ITEM_SK, s.LOCN_SK, s.QUANTITY, s.UNIT_PRICE, s.DISCOUNT_AMOUNT,
    s.NET_SALES, s.SOURCE_ROW_ID
)
