-- Weekly-store snapshots plus Day 3 exceptional snapshot.
-- Change detection tracks DISTRICT_ID, not the SCD1 descriptive DISTRICT_NAME.
CREATE OR REPLACE TEMPORARY TABLE RETAIL_DWH.TMP.WORK_DIM_LOCN AS
WITH source_snapshots AS (
    SELECT
        m.SOURCE_ROW_ID, m.SNAPSHOT_DATE, m.STORE_ID, m.STORE_NAME,
        m.CITY, m.REGION, m.DISTRICT_ID, d.DISTRICT_SK, m.IS_ACTIVE,
        m.LOCATION_TYPE,
        HASH(m.STORE_NAME, m.CITY, m.REGION, m.DISTRICT_ID,
             m.IS_ACTIVE, m.LOCATION_TYPE) AS RECORD_HASH
    FROM RETAIL_DWH.TMP.STORE_MASTER m
    INNER JOIN RETAIL_DWH.TGT.DIM_DISTRICT d
        ON m.DISTRICT_ID = d.DISTRICT_ID
), ranked AS (
    SELECT s.*,
        LAG(RECORD_HASH) OVER (
            PARTITION BY STORE_ID ORDER BY SNAPSHOT_DATE
        ) AS PREVIOUS_HASH
    FROM source_snapshots s
), boundaries AS (
    SELECT *
    FROM ranked
    WHERE PREVIOUS_HASH IS NULL OR RECORD_HASH <> PREVIOUS_HASH
)
SELECT
    b.SOURCE_ROW_ID, b.STORE_ID, b.STORE_NAME, b.CITY, b.REGION,
    b.DISTRICT_ID, b.DISTRICT_SK, b.IS_ACTIVE,
    b.LOCATION_TYPE,
    b.SNAPSHOT_DATE AS EFFECTIVE_FROM,
    LEAD(b.SNAPSHOT_DATE) OVER (
        PARTITION BY b.STORE_ID ORDER BY b.SNAPSHOT_DATE
    ) AS EFFECTIVE_TO,
    LEAD(b.SNAPSHOT_DATE) OVER (
        PARTITION BY b.STORE_ID ORDER BY b.SNAPSHOT_DATE
    ) IS NULL AS IS_CURRENT,
    b.RECORD_HASH
FROM boundaries b
