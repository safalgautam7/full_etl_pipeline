-- Close historical positions and add new effective-dated versions without
-- deleting old measures. One MERGE statement makes each position publication
-- atomic. Existing INVENTORY_VERSION_SK is never regenerated on reruns.
MERGE INTO RETAIL_DWH.TGT.FCT_INVENTORY t
USING RETAIL_DWH.TMP.WORK_FCT_INVENTORY s
  ON t.STORE_ID = s.STORE_ID
 AND t.ITEM_ID = s.ITEM_ID
 AND t.EFFECTIVE_FROM = s.EFFECTIVE_FROM
WHEN MATCHED AND (
    t.ITEM_SK IS DISTINCT FROM s.ITEM_SK OR
    t.LOCN_SK IS DISTINCT FROM s.LOCN_SK OR
    t.QUANTITY_ON_HAND IS DISTINCT FROM s.QUANTITY_ON_HAND OR
    t.UNIT_COST IS DISTINCT FROM s.UNIT_COST OR
    t.INVENTORY_VALUE IS DISTINCT FROM s.INVENTORY_VALUE OR
    t.EFFECTIVE_TO IS DISTINCT FROM s.EFFECTIVE_TO OR
    t.IS_CURRENT IS DISTINCT FROM s.IS_CURRENT OR
    t.SOURCE_ROW_ID IS DISTINCT FROM s.SOURCE_ROW_ID
) THEN UPDATE SET
    t.ITEM_SK = s.ITEM_SK,
    t.LOCN_SK = s.LOCN_SK,
    t.QUANTITY_ON_HAND = s.QUANTITY_ON_HAND,
    t.UNIT_COST = s.UNIT_COST,
    t.INVENTORY_VALUE = s.INVENTORY_VALUE,
    t.EFFECTIVE_TO = s.EFFECTIVE_TO,
    t.IS_CURRENT = s.IS_CURRENT,
    t.SOURCE_ROW_ID = s.SOURCE_ROW_ID,
    t.REC_UPDT_TS = CURRENT_TIMESTAMP()
WHEN NOT MATCHED THEN INSERT (
    STORE_ID, ITEM_ID, ITEM_SK, LOCN_SK,
    QUANTITY_ON_HAND, UNIT_COST, INVENTORY_VALUE,
    EFFECTIVE_FROM, EFFECTIVE_TO, IS_CURRENT, SOURCE_ROW_ID
) VALUES (
    s.STORE_ID, s.ITEM_ID, s.ITEM_SK, s.LOCN_SK,
    s.QUANTITY_ON_HAND, s.UNIT_COST, s.INVENTORY_VALUE,
    s.EFFECTIVE_FROM, s.EFFECTIVE_TO, s.IS_CURRENT, s.SOURCE_ROW_ID
)
