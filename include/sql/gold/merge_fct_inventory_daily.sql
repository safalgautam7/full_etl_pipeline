-- Natural grain: one accepted daily observation per store/item/date.
MERGE INTO RETAIL_DWH.TGT.FCT_INVENTORY_DAILY t
USING RETAIL_DWH.TMP.WORK_INV_OBSERVATIONS s
  ON t.STORE_ID = s.STORE_ID AND t.ITEM_ID = s.ITEM_ID
 AND t.SNAPSHOT_DATE = s.SNAPSHOT_DATE
WHEN MATCHED AND (
    t.ITEM_SK IS DISTINCT FROM s.ITEM_SK OR t.LOCN_SK IS DISTINCT FROM s.LOCN_SK OR
    t.QUANTITY_ON_HAND IS DISTINCT FROM s.QUANTITY_ON_HAND OR
    t.UNIT_COST IS DISTINCT FROM s.UNIT_COST OR
    t.INVENTORY_VALUE IS DISTINCT FROM s.INVENTORY_VALUE OR
    t.SOURCE_ROW_ID IS DISTINCT FROM s.SOURCE_ROW_ID
) THEN UPDATE SET
    t.ITEM_SK = s.ITEM_SK, t.LOCN_SK = s.LOCN_SK,
    t.QUANTITY_ON_HAND = s.QUANTITY_ON_HAND, t.UNIT_COST = s.UNIT_COST,
    t.INVENTORY_VALUE = s.INVENTORY_VALUE, t.SOURCE_ROW_ID = s.SOURCE_ROW_ID,
    t.REC_UPDT_TS = CURRENT_TIMESTAMP()
WHEN NOT MATCHED THEN INSERT (
    SNAPSHOT_DATE_KEY, SNAPSHOT_DATE, STORE_ID, ITEM_ID, ITEM_SK, LOCN_SK,
    QUANTITY_ON_HAND, UNIT_COST, INVENTORY_VALUE, SOURCE_ROW_ID
) VALUES (
    TO_NUMBER(TO_CHAR(s.SNAPSHOT_DATE, 'YYYYMMDD')), s.SNAPSHOT_DATE,
    s.STORE_ID, s.ITEM_ID, s.ITEM_SK, s.LOCN_SK,
    s.QUANTITY_ON_HAND, s.UNIT_COST, s.INVENTORY_VALUE, s.SOURCE_ROW_ID
)
