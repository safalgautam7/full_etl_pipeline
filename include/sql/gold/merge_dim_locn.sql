-- SCD Type 2 for locations. A district change inserts a new historical version.
MERGE INTO RETAIL_DWH.TGT.DIM_LOCN t
USING RETAIL_DWH.TMP.WORK_DIM_LOCN s
ON t.STORE_ID = s.STORE_ID AND t.EFFECTIVE_FROM = s.EFFECTIVE_FROM
WHEN MATCHED AND (
    t.RECORD_HASH IS DISTINCT FROM s.RECORD_HASH OR
    t.SOURCE_ROW_ID IS DISTINCT FROM s.SOURCE_ROW_ID OR
    t.EFFECTIVE_TO IS DISTINCT FROM s.EFFECTIVE_TO OR
    t.IS_CURRENT IS DISTINCT FROM s.IS_CURRENT OR
    t.DISTRICT_SK IS DISTINCT FROM s.DISTRICT_SK
) THEN UPDATE SET
    t.STORE_NAME = s.STORE_NAME,
    t.CITY = s.CITY,
    t.REGION = s.REGION,
    t.DISTRICT_ID = s.DISTRICT_ID,
    t.DISTRICT_SK = s.DISTRICT_SK,
    t.IS_ACTIVE = s.IS_ACTIVE,
    t.EFFECTIVE_TO = s.EFFECTIVE_TO,
    t.IS_CURRENT = s.IS_CURRENT,
    t.RECORD_HASH = s.RECORD_HASH,
    t.SOURCE_ROW_ID = s.SOURCE_ROW_ID,
    t.REC_UPDT_TS = CURRENT_TIMESTAMP()
WHEN NOT MATCHED THEN INSERT (
    STORE_ID, STORE_NAME, CITY, REGION, DISTRICT_ID, DISTRICT_SK,
    IS_ACTIVE, EFFECTIVE_FROM, EFFECTIVE_TO, IS_CURRENT,
    RECORD_HASH, SOURCE_ROW_ID
) VALUES (
    s.STORE_ID, s.STORE_NAME, s.CITY, s.REGION, s.DISTRICT_ID, s.DISTRICT_SK,
    s.IS_ACTIVE, s.EFFECTIVE_FROM, s.EFFECTIVE_TO, s.IS_CURRENT,
    s.RECORD_HASH, s.SOURCE_ROW_ID
)
