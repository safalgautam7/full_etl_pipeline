-- SCD Type 1: store the latest district description.
-- The two-store-snapshot fixture does NOT include the optional Day 5 rename.
MERGE INTO RETAIL_DWH.TGT.DIM_DISTRICT t
USING (
    SELECT DISTRICT_ID, DISTRICT_NAME
    FROM RETAIL_DWH.TMP.STORE_MASTER
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY DISTRICT_ID
        ORDER BY SNAPSHOT_DATE DESC, SOURCE_FILE_NAME DESC,
                 SOURCE_ROW_NUMBER DESC, SOURCE_ROW_ID DESC
    ) = 1
) s
ON t.DISTRICT_ID = s.DISTRICT_ID
WHEN MATCHED AND t.DISTRICT_NAME IS DISTINCT FROM s.DISTRICT_NAME THEN
    UPDATE SET
        t.DISTRICT_NAME = s.DISTRICT_NAME,
        t.UPDATED_AT = CURRENT_TIMESTAMP()
WHEN NOT MATCHED THEN
    INSERT (DISTRICT_ID, DISTRICT_NAME)
    VALUES (s.DISTRICT_ID, s.DISTRICT_NAME)
